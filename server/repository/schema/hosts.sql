-- hosts: hosts started by users with `ama daemon` on their own machines (Mac/Linux).
--
-- # Why this table exists
--
-- By default agents run tools in a Docker container. The host executor lets users register their own
-- fixed machines (a company Mac, a personal dev machine): the daemon stays running locally, and amad
-- sends the six tools (bash/read/write/edit/glob/grep) to that machine through HTTP long polling. Host
-- information is an **account-level** resource (owned by whoever registered it); workspace binding is
-- another table, workspace_hosts.
--
-- # Identity and revocation: the token is stored only as sha256
--
-- When the daemon registers, the server generates a random host_token; the plain text is returned
-- once and kept in ~/.ama/host.json on the daemon's machine; the database only stores the sha256. The
-- daemon's heartbeat/result routes are on the bare mux and authenticate through this table with
-- Authorization: Bearer <host_token>. Deleting the host revokes it, the same model as auth_api_keys
-- (see auth/apikey.go), so these routes do not use user API Keys (to avoid a TouchAPIKey PG write on
-- every 20s heartbeat).
--
-- # host_uuid and uniqueness of (owner_email, host_uuid)
--
-- host_uuid is a random id generated by the daemon on the machine at first start, tied to the
-- credential file on the machine. Running `ama daemon run` repeatedly on the same machine (restart,
-- upgrade) must hit the same row instead of creating a new host; different people each registering
-- the same machine (a shared dev machine) get different rows, so the unique key includes owner_email.
-- id (hst_ prefix) is the opaque primary key exposed inside and out; URLs are not built from the uuid
-- directly.
--
-- # How status / last_seen_at are maintained
--
-- Only by heartbeats: a heartbeat refreshes last_seen_at and sets online; core/hostwatcher, with
-- leader election across instances, sets hosts whose last_seen_at is older than 90s to offline (CAS,
-- only updating online rows). Reading this column is enough to know who is online; no in-process
-- registry is kept: in-process state is bound to disagree across instances.
--
-- # gnu_tools_ok / toolcheck (old protocol fields, only for old daemons)
--
-- The old six tools sent GNU coreutils dialect scripts, and the daemon probed at startup whether the
-- brew GNU tools were all there. The new protocol (dispatch kind='tool', executed natively in Go by
-- the daemon; see docs/guides/host-executor.md) no longer needs these external tools, and the gate
-- looks at native_tools instead. The two columns only exist to accept heartbeats from old daemons.
--
-- # native_tools
--
-- Whether the daemon supports the structured native tool protocol (kind='tool'). New daemons always
-- report true; when false (old versions), calls of the six tools are rejected on the server with
-- "please upgrade ama daemon", instead of sending calls it cannot run.
create table if not exists hosts (
    id             text        not null,
    owner_email    text        not null,

    -- Host name (hostname), for people; duplicates and renames are allowed, and it takes part in no
    -- routing.
    name           text        not null default '',

    -- darwin / linux and amd64 / arm64. Two separate columns; the daemon reports runtime.GOOS/GOARCH
    -- when registering.
    os             text        not null default '',
    arch           text        not null default '',

    -- The random uuid generated by the daemon on the machine; see the file header.
    host_uuid      text        not null default '',

    -- sha256 of host_token; '' means not issued yet (should not last long).
    token_hash     text        not null default '',

    -- online / offline, no CHECK (consistent across the repository); NULL/'' reads as offline.
    status         text        not null default '',

    daemon_version text        not null default '',
    gnu_tools_ok   boolean     not null default false,
    -- Failure details of the GNU tool probe, a diagnostic field of the old protocol; see "old
    -- protocol fields" in the file header.
    toolcheck      text        not null default '',
    -- Supports the native tool protocol (kind='tool'); old daemons default to false.
    native_tools   boolean     not null default false,

    created_at     timestamptz not null,
    last_seen_at   timestamptz,

    -- Per-host downlink command counter. The sequence number cannot be looked up as max(seq) of
    -- host_dispatches at enqueue time: done rows get cleared entirely by PurgeOldTermDispatches /
    -- PurgeDoneExecDispatches, after which the next one would be numbered from 1 again, while the
    -- daemon's persisted last_seq is a large number, so `seq > last_seq` would never hold, and new
    -- commands would silently never be pulled. The counter lives on hosts, decoupled from the
    -- lifetime of dispatch rows.
    last_dispatch_seq bigint   not null default 0,

    constraint hosts_pkey primary key (id)
);

create unique index if not exists hosts_owner_uuid_idx
    on hosts (owner_email, host_uuid);

-- Used by the global settings page to list "my hosts", in ascending order of registration time.
create index if not exists hosts_owner_idx
    on hosts (owner_email, created_at);

-- hostwatcher scans hosts that "may have gone offline" each round: only online ones with no
-- heartbeat for 90s. There is no status condition so the same index can scan online-but-lost hosts
-- and also look into rows that were never online.
create index if not exists hosts_last_seen_idx
    on hosts (last_seen_at);
