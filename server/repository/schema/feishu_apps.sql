-- feishu_apps: connected Feishu apps.
create table if not exists feishu_apps (
    -- id is the AMA-side identifier (fsa_xxx), generated by the business layer, not a database
    -- sequence.
    id           text        not null,
    -- workspace_id is the owning workspace; ListApps filters by it.
    workspace_id text        not null,
    -- app_id is the Feishu app ID (cli_xxx), globally unique.
    app_id       text        not null,
    -- app_secret is the app secret.
    --
    -- **It may be NULL, and NULL means something different from an empty string.** In the memory
    -- implementation secrets are in a separate map, and CreateApp with an empty string never writes
    -- into that map, so AppSecret() returns ErrAppNotFound rather than ("", nil). Using NULL for "this
    -- item does not exist" matches that behavior; storing an empty string would make AppSecret return
    -- an empty string plus nil, differing from the memory implementation.
    --
    -- It **only flows inside this package**: the App struct has no such field, so the secret cannot
    -- get into any response.
    app_secret   text,
    -- created_at is the connection time; the list is in ascending order of it.
    --
    -- Note timestamptz only has microsecond precision, while createdAt in doc is in nanoseconds. So it
    -- is only used to let the SQL side use the index for a roughly ordered result; the final order is
    -- settled by the Go side sorting by doc once more (see ListApps in store_pg.go).
    created_at   timestamptz not null,
    -- doc is the JSON of the whole App struct. The columns above are copies pulled out of it.
    doc          jsonb       not null,

    constraint feishu_apps_pkey     primary key (id),
    -- Idempotent registration relies on this unique constraint: a clash means "this Feishu app is
    -- already connected". It is named explicitly so the Go side can tell it apart from a primary key
    -- conflict with pg.ConstraintName: both are 23505, but only the former should become
    -- ErrAppExists.
    constraint feishu_apps_app_id_key unique (app_id)
);

-- The composite index used by the list query; the column order matches
-- `where workspace_id = $1 order by created_at, id`.
create index if not exists feishu_apps_workspace_created_idx
    on feishu_apps (workspace_id, created_at, id);

comment on column feishu_apps.app_secret is
    'Feishu AppSecret. NULL means no secret (matches the missing key in the in-memory secrets map); not the same as an empty string.';
