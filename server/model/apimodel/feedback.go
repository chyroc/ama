// Public shape of problem feedback (Feedback).
//
// ⚠️ It is **not the same thing** as "issues" (Issue) or "product suggestions" (Suggestion); see
// core/README-feedback.md.
//
// FeedbackLevel used to live in storemodel, but FeedbackReport.Level uses it, and
// FeedbackReport goes into HTTP responses; leaving it in storemodel would make domain import it in reverse
// (storemodel already imports domain; that is a cycle). So it moved here along with it,
// and storemodel keeps a one-line type alias.

package apimodel

// FeedbackLevel is the two levels of feedback.
type FeedbackLevel string

const (
	// FeedbackAuto is recorded automatically when an error happens, without the user clicking anything. **The smallest collection surface.**
	FeedbackAuto FeedbackLevel = "auto"
	// FeedbackUser is submitted by the user clicking "Report this problem". **That click is their consent.**
	FeedbackUser FeedbackLevel = "user"
)

// FeedbackInput is what the report endpoint accepts.
//
// ⚠️ **This struct is the allowlist itself.** Beyond the fields it lists, nothing the frontend sends gets in:
// encoding/json drops unknown keys. So the question "could a sensitive field slip through" has a definite answer
// here: no, because we are not deleting fields, we are picking fields.
//
// Before adding a field, ask: does **level one** need to collect this too? If unsure, give it to level two only
// (just do not read it in sanitizeAuto); that is the safe default.
type FeedbackInput struct {
	// Level is "auto" or "user"; anything unrecognized is rejected.
	Level string `json:"level"`

	// RoutePattern is the route pattern computed by the frontend, **with ids already stripped**.
	//
	// ⚠️ Computed by the frontend rather than parsed by the backend from Referer: the backend does not have the frontend's route table, and the meaning of SPA paths
	// (which segment is an id) is only known to the frontend. **But the backend still strips it again** (see stripRouteIDs):
	// when the frontend gets it wrong or a caller hits this endpoint directly, paths containing ids would break dedup and aggregation.
	RoutePattern string `json:"routePattern"`

	// HTTPStatus / ErrorCode / ErrorKind are the three fields for finding the cause, from AsyncError.
	HTTPStatus int    `json:"httpStatus"`
	ErrorCode  string `json:"errorCode"`
	ErrorKind  string `json:"errorKind"`

	// Message is the error text the user saw.
	//
	// **Both levels collect it**, because it is a sentence the backend produced itself (not user input), and it often directly
	// names the cause. It still goes through scrubText: the backend's error text could in theory carry upstream content.
	Message string `json:"message"`

	// WorkspaceID is the workspace where the problem happened. May be empty.
	WorkspaceID string `json:"workspaceId"`

	// Browser / OS are a **summary** of the browser and system ("Chrome 120" / "macOS").
	//
	// ⚠️ Deliberately **does not collect the raw UA string**: the raw UA has fingerprinting value (it can identify a specific device and version combination),
	// while debugging only needs "which browser, which system". The frontend summarizes before sending, and the backend does not parse UA:
	// that is a notoriously bad job, and we do not need that precision.
	Browser string `json:"browser"`
	OS      string `json:"os"`

	// AppVersion is the frontend version (the git sha injected at build time).
	AppVersion string `json:"appVersion"`

	// LogID is **the server-side logid of this request** (response header X-TT-Logid, written by httpd's withLogID).
	// **Both levels collect it.**
	//
	// # What it buys
	//
	// With it, one feedback entry can go straight to all log lines of that request in the log system (logs take the logid from ctx
	// and print it), without guessing by "roughly what time + which endpoint": under concurrency timestamps collide,
	// so that kind of guessing is unreliable anyway. Errors that need cross-side debugging like 403 / 404 / 409 / 500 benefit most.
	//
	// # Why level one collects it too (it needs no user consent)
	//
	// This string is **generated by our own server**, contains no user input, and is not a credential;
	// when shared/infra/secret deliberately does not scrub bare hex, it even names "logid is debugging info that should not be redacted".
	//
	// And **level one already knows who reported this feedback** (the actor column stores the employee email),
	// so adding the logid exposes no extra identity. Level one is exactly the level that needs it most:
	// those records have no user beside them to explain "what I was doing then"; only a logid can tie it back to the scene.
	//
	// # ⚠️ Under network_error the frontend cannot provide it; that is not a missing value
	//
	// fetch only rejects when the network layer fails, and then **the request never reached the server**: the withLogID
	// HTTP middleware never ran, no id was generated, and there is not a single line of this request
	// in the server logs. So receiving an empty string in that case is correct; **do not give it any placeholder value**
	// (same as the LogIDDefault "-" banned by core/observe.go:
	// that is a valid string and would be reported as a real logid; when debugging you would think it is linked, while it is fake).
	//
	// # ⚠️ It must never go into dedup_key
	//
	// logid is unique per request; in the dedup key every entry would count as a new row, and **rate limiting would stop working entirely**: that is exactly how this feature
	// would DoS itself, with no error. feedbackDedupKey does not read it, and TestFeedbackLogIDIsNotInDedupKey
	// pins this. **This is the only thing that became dangerous after "level one collects it too"**, because only level one goes through dedup.
	LogID string `json:"logId"`

	// APIRoute is the route pattern of **the endpoint that failed this time** (`POST /api/workspaces/{id}/agents`).
	// **Both levels collect it.**
	//
	// # It fills a real blind spot
	//
	// `RoutePattern` is the **page** route (which screen the user is on), not the **endpoint** route. The two
	// often differ: the `/w/{id}/chat` page calls a dozen different endpoints, and level one
	// **does not collect `Recent`**, so before this, level-one records could not tell "which endpoint failed" at all.
	//
	// That is exactly the first question when debugging: with it you can aggregate by route directly in the log system
	// ("how many times did this endpoint fail today"), which is exactly the first query for automated improvement.
	//
	// # Why it is not sensitive (checked item by item against the "never collected at either level" table)
	//
	//   - It is **a route pattern, not a real path**: id segments are already turned into `{id}` by the frontend, and the backend strips again
	//     (stripRouteIDs, same rule as RoutePattern). So it cannot locate a specific session or agent,
	//     and level one's boundary "no full paths" is not bypassed.
	//   - **No query**: the frontend already did stripQuery when recording, the same path as FeedbackCall.Path.
	//   - No user input, no response body, not a credential. It is one item in our own endpoint list,
	//     which `GET /api/openapi.json` already makes public.
	//   - Low cardinality, so `group by` makes sense; and it **does not go into dedup_key** (reason below).
	//
	// # ⚠️ Not in dedup_key
	//
	// Not because it is dangerous (it has low cardinality and would not break rate limiting like logid), but because
	// **it is not needed**: `route_pattern + error_code + http_status` already pins down "the same kind of problem",
	// and one more dimension would only split rows that should merge. The dedup key is unchanged,
	// and TestAutoFeedbackIsRateLimited still pins this.
	APIRoute string `json:"apiRoute"`

	// APIMethod is the HTTP method of that failed call (GET / POST / PATCH / DELETE). **Both levels collect it.**
	//
	// Kept apart from APIRoute instead of joined into one string: GET and DELETE on the same path are two
	// different problems (cannot read vs cannot delete); joined, you cannot aggregate one of them alone.
	// It is one of four fixed values, with no user data at all.
	APIMethod string `json:"apiMethod"`

	// -- Only level two uses the following (sanitizeAuto never reads them) -------------------

	// Path is **the full path, with ids**. Only level two collects it.
	//
	// Level one does not, because the ids in the path (sessionId / runId / agentId) can locate one specific
	// chat, and the user never consented. Level two does, because "which session had the problem" is where debugging starts.
	Path string `json:"path"`

	// Recent is a summary of the last few endpoint calls. Only level two collects it, and **each item is also an allowlist**
	// (see FeedbackCall).
	Recent []FeedbackCall `json:"recent"`

	// ConsoleErrors is the **first line** of the last few console errors. Only level two collects it.
	ConsoleErrors []string `json:"consoleErrors"`

	// AgentID identifies the current agent. Only level two collects it.
	AgentID string `json:"agentId"`
}

// FeedbackCall is a summary of one endpoint call. **Also an allowlist**: no body, no response body,
// no request headers, only "which endpoint was called and how it went".
//
// ⚠️ In particular **there is no query part of the URL**: the query may contain a token (historically the frontend really did put
// identity into ?actor=, see the comment in http.ts). Only the method and path pattern are kept.
type FeedbackCall struct {
	Method string `json:"method"`
	// Path is the endpoint path; **stripRouteIDs strips id segments and cuts off the query**.
	Path   string `json:"path"`
	Status int    `json:"status"`
	Code   string `json:"code"`
	// LogID is the server-side logid of that request; **an empty string when not available**.
	//
	// This one can save the network_error case: the failing request itself has no logid (it never arrived),
	// but if the user used things normally for a while before the backend went down, the earlier failures that **did reach** the server
	// each carry a real logid, and following them locates the moment the backend went down.
	LogID string `json:"logId"`
}

// FeedbackReport is the public shape of one feedback entry (an element of the read endpoint's response).
//
// Field names are camelCase (the convention for AMA's own entities; see the top of model/apimodel).
type FeedbackReport struct {
	ID    string        `json:"id"`
	Level FeedbackLevel `json:"level"`
	// Actor is the person who hit the problem (employee email).
	Actor string `json:"actor"`
	// WorkspaceID may be empty: errors can happen outside a workspace (the workspace list page, preferences, a newcomer who has not joined
	// any workspace yet). **Has omitempty**; the frontend only checks truthiness.
	WorkspaceID string `json:"workspaceId,omitempty"`
	// RoutePattern is the route pattern with ids stripped, like /w/{key}/chat/{runId}.
	RoutePattern string `json:"routePattern"`
	// HTTPStatus is 0 when not available. **No omitempty**: 0 is a valid value (a network failure has no response at all),
	// and a missing key would make the frontend compute undefined. This is one more case of the hard rule "numbers have no omitempty"
	// in model/apimodel.
	HTTPStatus int `json:"httpStatus"`
	// ErrorCode is the backend error code (access_denied / network_error…); empty string when not available.
	ErrorCode string `json:"errorCode"`
	// ErrorKind is the frontend category (denied / other).
	ErrorKind string `json:"errorKind"`
	// UserAgent is the browser summary (Chrome 120 / macOS), not the raw UA string.
	UserAgent string `json:"userAgent"`
	// LogID is the server-side logid of that request; **both levels collect it**.
	//
	// Has omitempty: when empty this key **does not appear at all**, instead of appearing as an empty string.
	// There is only one reason for it to be empty: failed requests like network_error never reached the server,
	// and no logid was ever generated (see FeedbackInput.LogID).
	// The key being absent means "there are no server logs this time", which is more honest than an empty string.
	LogID string `json:"logId,omitempty"`
	// Payload is the remaining details. **The field sets of level one and level two are deliberately different.**
	//
	// No omitempty, and guaranteed non-nil: the frontend iterates it directly, and null would blow up.
	Payload map[string]any `json:"payload"`
	// CreatedAt / LastSeenAt are fixed-length ISO strings (same as the rest of the site; see NowISO).
	CreatedAt  string `json:"createdAt"`
	LastSeenAt string `json:"lastSeenAt"`
	// Occurrences is how many times this entry was hit. After level-one dedup it keeps the magnitude; level two is always 1.
	Occurrences int `json:"occurrences"`
}

// FeedbackPage is the response of the read endpoint.
//
// It carries Total instead of just an array: callers (automation scripts) need to know "is there a next page",
// and judging by "does this page have Limit items" is wrong when the last page happens to be exactly full.
type FeedbackPage struct {
	// Reports is non-nil; when empty it is [] (the frontend/scripts iterate it directly).
	Reports []FeedbackReport `json:"reports"`
	Total   int              `json:"total"`
	Limit   int              `json:"limit"`
	Offset  int              `json:"offset"`
}
