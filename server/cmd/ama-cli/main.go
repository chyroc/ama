func (c *client) whoami() error {
	// There is no dedicated whoami API, so "list the workspaces I am in" stands in: it verifies the
	// credential works and also tells the agent which workspaces it can touch.
	raw, err := c.do(http.MethodGet, "/api/workspaces", nil)
	if err != nil {
		return err
	}
	fmt.Printf("服务地址: %s\n", c.baseURL)
	if c.workspaceID != "" {
		fmt.Printf("当前空间: %s（来自 %s，多数命令默认用它）\n", c.workspaceID, envWorkspaceID)
	} else {
		fmt.Printf("当前空间: 未注入（%s 是空的，需要空间的命令要显式带 --workspace）\n", envWorkspaceID)
	}
	fmt.Println("我能访问的空间:")
	return printJSON(raw)
}

