func (c *client) issue(args []string) error {
	sub := first(args)
	switch sub {
	case "", "list":
		ws, err := c.wsID(args[1:])
		if err != nil {
			return err
		}
		raw, err := c.do(http.MethodGet, "/api/workspaces/"+url.PathEscape(ws)+"/issues", nil)
		if err != nil {
			return err
		}
		return printJSON(raw)

	case "get":
		id, _ := shiftPositional(args[1:])
		if id == "" {
			return errors.New("要问题 id：ama issue get <id>")
		}
		raw, err := c.do(http.MethodGet, "/api/issues/"+url.PathEscape(id), nil)
		if err != nil {
			return err
		}
		return printJSON(raw)

	case "create":
		flags := parseFlags(args[1:])
		ws, err := c.wsIDFrom(flags)
		if err != nil {
			return err
		}
		title, body := flags["title"], flags["body"]
		// The server also rejects it (400), but block it here first: that 400 costs a round of tool
		// calls to see, while this check is deterministic. ⚠️ The rule comes from the IssueDraft
		// schema, not something we made up.
		if strings.TrimSpace(title) == "" && strings.TrimSpace(body) == "" {
			return errors.New("--title 与 --body 至少要给一个（两个都空会被服务端拒）")
		}
		draft := map[string]string{}
		putIf(draft, "title", title)
		putIf(draft, "body", body)
		putIf(draft, "status", flags["status"])
		putIf(draft, "priority", flags["priority"])
		raw, err := c.do(http.MethodPost, "/api/workspaces/"+url.PathEscape(ws)+"/issues", draft)
		if err != nil {
			return err
		}
		return printJSON(raw)

	case "comment":
		id, rest := shiftPositional(args[1:])
		if id == "" {
			return errors.New("要问题 id：ama issue comment <id> --body \"...\"")
		}
		flags := parseFlags(rest)
		body := strings.TrimSpace(flags["body"])
		if body == "" {
			return errors.New("要 --body：ama issue comment <id> --body \"评论内容\"")
		}
		raw, err := c.do(http.MethodPost,
			"/api/issues/"+url.PathEscape(id)+"/comments",
			map[string]string{"body": body})
		if err != nil {
			return err
		}
		return printJSON(raw)

	case "comments":
		id, _ := shiftPositional(args[1:])
		if id == "" {
			return errors.New("要问题 id：ama issue comments <id>")
		}
		raw, err := c.do(http.MethodGet, "/api/issues/"+url.PathEscape(id)+"/comments", nil)
		if err != nil {
			return err
		}
		return printJSON(raw)

	case "update":
		id, rest := shiftPositional(args[1:])
		if id == "" {
			return errors.New("要问题 id：ama issue update <id> [--status ...] [--priority ...]")
		}
		flags := parseFlags(rest)
		hasAny := false
		for _, k := range []string{"title", "body", "status", "priority"} {
			if _, ok := flags[k]; ok {
				hasAny = true
			}
		}
		if !hasAny {
			return errors.New("没有要改的字段。可用：--title / --body / --status / --priority")
		}

		// ⚠️ **It must be read back first, and title/body sent back together.**
		//
		// `PATCH /api/issues/{id}` sounds like a partial update, but for title/body it is a **full
		// replacement**: UpdateIssue in core/issue.go unconditionally runs `next.Title = draft.Title` /
		// `next.Body = draft.Body`, so a "change only the status" request (without title/body) would
		// clear both, and then be rejected with 400 "please fill in at least a title or body".
		//
		// This trap was actually hit: `ama issue update <id> --status closed` gave a straight 400,
		// **and the error said "please fill in at least a title or body", not pointing at "you left
		// out title" at all**. Only status/priority are "not sent means not changed".
		cur, err := c.do(http.MethodGet, "/api/issues/"+url.PathEscape(id), nil)
		if err != nil {
			return err
		}
		var issue struct {
			Title string `json:"title"`
			Body  string `json:"body"`
		}
		if err := json.Unmarshal(cur, &issue); err != nil {
			return fmt.Errorf("读回这条问题失败：%w", err)
		}

		patch := map[string]string{
			// Fill in the current values first, then let explicitly given parameters override them, so "fields not mentioned" stay as they are.
			"title": issue.Title,
			"body":  issue.Body,
		}
		for _, k := range []string{"title", "body", "status", "priority"} {
			if v, ok := flags[k]; ok {
				patch[k] = v
			}
		}
		raw, err := c.do(http.MethodPatch, "/api/issues/"+url.PathEscape(id), patch)
		if err != nil {
			return err
		}
		return printJSON(raw)

	default:
		return fmt.Errorf("issue 没有 %q 子命令，可用：list / get / create / update / comment / comments", sub)
	}
}

// rawAPI is the escape hatch: call any API directly.
//
// It exists **so the agent does not have to hand-write curl**. Hand-written curl inevitably puts the
// token on the command line (`-H "Authorization: Bearer $AMA_TOKEN"`), and the command line goes as
// is into RunEvent as a permanent record. With this hatch, the credential only ever stays in env.
//
// ⚠️ It does not widen permissions: what can be called is decided on the amad side, whether or not
// this hatch is used.
func (c *client) rawAPI(args []string) error {
	// Take the flags out first; what remains are the positional arguments.
	//
	// ⚠️ Without taking them out, `ama api DELETE /api/issues/x --yes` would treat `--yes` as the
	// JSON body and report "not valid JSON"; **that error does not point at the real cause at all**
	// (the user thinks their JSON is wrong, while no body was passed at all). This was actually hit,
	// so filter by prefix here instead of taking by position.
	confirmed := hasConfirm(args)
	positional := make([]string, 0, len(args))
	for _, a := range args {
		if strings.HasPrefix(a, "--") {
			continue
		}
		positional = append(positional, a)
	}

	if len(positional) < 2 {
		return errors.New("用法：ama api <METHOD> <PATH> [JSON体]\n" +
			"例：ama api GET /api/workspaces\n" +
			"    ama api POST /api/workspaces/ws_x/issues '{\"title\":\"标题\"}' --yes\n" +
			"PATH 要以 / 开头。不知道有哪些接口就跑 `ama api-doc`")
	}
	method := strings.ToUpper(positional[0])
	path := positional[1]
	if !strings.HasPrefix(path, "/") {
		return fmt.Errorf("PATH 要以 / 开头，你给的是 %q", path)
	}

	var body any
	if len(positional) > 2 && strings.TrimSpace(positional[2]) != "" {
		// Parse it once first, so a wrong shape errors here; earlier and more precise than letting the server return 400.
		if err := json.Unmarshal([]byte(positional[2]), &body); err != nil {
			return fmt.Errorf("请求体不是合法 JSON：%w\n收到的是：%s", err, positional[2])
		}
	}

	// Write operations need explicit confirmation; see the confirmFlag comment.
	if isWriteMethod(method) && !confirmed {
		return fmt.Errorf("这是一个写操作（%s）。确认要做再加 --yes 重跑同一条命令。\n"+
			"（先向用户说明你要改什么、拿到同意再执行）", method)
	}

	raw, err := c.do(method, path, body)
	if err != nil {
		return err
	}
	// DELETE and the like may return an empty body (204); then print a confirmation line instead of an
	// empty line; seeing empty output, the agent would suspect the command did not run.
	if len(strings.TrimSpace(string(raw))) == 0 {
		fmt.Printf("成功（%s %s，服务端没有返回内容）\n", method, path)
		return nil
	}
	return printJSON(raw)
}

// isWriteMethod tells whether a method changes data.
func isWriteMethod(m string) bool {
	switch m {
	case http.MethodPost, http.MethodPut, http.MethodPatch, http.MethodDelete:
		return true
	}
	return false
}

// confirmFlag is the write-operation gate of `ama api`.
//
// # What it guards against, and what it does not
//
// **Guards against**: one model hallucination breaking data. The extra step "rerun with --yes" gives
// it a natural pause, and gives "what I am about to change" a chance to be said to the user first.
//
// **Does not guard against**: a malicious agent. It can just add --yes, or curl with the token from
// env. The real boundary is on the amad side. **These two must not be mixed up**: believing the
// client gate gives real protection leads to leaving that restriction off the server.
//
// It is only on `ama api`, not on named subcommands like `issue create`: the latter have a clear
// meaning (the agent knows it is creating an issue), while `api` can hit any path, a completely
// different risk surface.
const confirmFlag = "--yes"

func hasConfirm(args []string) bool {
	for _, a := range args {
		if a == confirmFlag {
			return true
		}
	}
	return false
}

// hasFlag tells whether args contains a boolean switch (like --dry-run).
//
// Both the bare form (`--dry-run`) and the valued form (`--dry-run=true` / `=1` / `=yes`) count as
// "on"; explicit false values (`=false` / `=0` / `=no` / `=off`) count as "off".
//
// ⚠️ **parseFlags must not be used for this kind of switch**: parseFlags takes "the first token after
// --k that does not start with --" as k's value, so `ama skill upload --dry-run foo.zip` would eat
// foo.zip as dry-run's value; the switch looks like it worked, the file argument is gone, and the
// error says "no path given", not pointing at the real cause at all.
//
// ⚠️ **The valued form must be recognized too**: missing it means **silently doing the wrong thing**:
// `--dry-run=true` would be treated as "no dry-run given", so an operation that should only preview
// without saving would really create the skill, with no hint at all. parseFlags supports `--k=v`, and
// agents follow that habit, so this is not hypothetical input.
//
// ⚠️ `hasConfirm` deliberately **does not** use this function: `--yes` is the write confirmation gate,
// and `--yes=false` must count as "not confirmed"; while this function takes the conservative "count
// as on" direction for unrecognized values (safe for preview switches, exactly the opposite for
// confirmation switches). The meanings differ; do not merge them.
func hasFlag(args []string, flag string) bool {
	for _, a := range args {
		if a == flag {
			return true
		}
		v, ok := strings.CutPrefix(a, flag+"=")
		if !ok {
			continue
		}
		switch strings.ToLower(strings.TrimSpace(v)) {
		case "false", "0", "no", "off":
			return false
		default:
			return true
		}
	}
	return false
}

