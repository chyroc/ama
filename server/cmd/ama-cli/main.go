// wsID gets the workspace id: --workspace first, falling back to the injected AMA_WORKSPACE_ID.
func (c *client) wsID(args []string) (string, error) {
	return c.wsIDFrom(parseFlags(args))
}

func (c *client) wsIDFrom(flags map[string]string) (string, error) {
	if v := strings.TrimSpace(flags["workspace"]); v != "" {
		return v, nil
	}
	if c.workspaceID != "" {
		return c.workspaceID, nil
	}
	return "", fmt.Errorf(
		"不知道用哪个空间：%s 没注入，也没给 --workspace。\n"+
			"用 `ama workspace list` 看有哪些空间，取其中的 `id`（形如 ws_xxx）。\n"+
			"⚠️ 注意要 id 不是 key——URL 里那个短名是 key，接口要 id。", envWorkspaceID)
}

// parseFlags parses --k v and --k=v, ignoring everything else.
//
// The flag package is deliberately not used: it does os.Exit(2) on unknown arguments and prints its
// own usage, while we want our own errors that "tell the agent what to do next".
func parseFlags(args []string) map[string]string {
	out := map[string]string{}
	for i := 0; i < len(args); i++ {
		a := args[i]
		if !strings.HasPrefix(a, "--") {
			continue
		}
		name := strings.TrimPrefix(a, "--")
		if j := strings.Index(name, "="); j >= 0 {
			out[name[:j]] = name[j+1:]
			continue
		}
		if name == strings.TrimPrefix(confirmFlag, "--") {
			out[name] = "true"
			continue
		}
		if i+1 < len(args) && !strings.HasPrefix(args[i+1], "--") {
			out[name] = args[i+1]
			i++
		} else {
			out[name] = "true"
		}
	}
	return out
}

// shiftPositional takes the first non-flag argument and returns it plus the rest.
func shiftPositional(args []string) (string, []string) {
	for i, a := range args {
		if !strings.HasPrefix(a, "--") {
			rest := make([]string, 0, len(args)-1)
			rest = append(rest, args[:i]...)
			rest = append(rest, args[i+1:]...)
			return a, rest
		}
	}
	return "", args
}

func first(args []string) string {
	if len(args) == 0 {
		return ""
	}
	if strings.HasPrefix(args[0], "--") {
		return ""
	}
	return args[0]
}

func putIf(m map[string]string, k, v string) {
	if strings.TrimSpace(v) != "" {
		m[k] = v
	}
}

// printPick picks the entry with the matching id from a JSON array.
func printPick(raw []byte, id string) error {
	var list []map[string]any
	if err := json.Unmarshal(raw, &list); err != nil {
		return printJSON(raw)
	}
	for _, it := range list {
		if fmt.Sprint(it["id"]) == id || fmt.Sprint(it["key"]) == id {
			b, _ := json.MarshalIndent(it, "", "  ")
			fmt.Println(string(b))
			return nil
		}
	}
	return fmt.Errorf("在你能访问的空间里没有 %q。跑 `ama workspace list` 看有哪些", id)
}

