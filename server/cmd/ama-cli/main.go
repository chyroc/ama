// version is injected at build time (-ldflags "-X main.version=..."), dev by default.
//
// It is kept the same as the npm package version; the `bin/ama.js` shell uses it to decide whether
// to download again.
var version = "dev"

const (
	envToken       = "AMA_TOKEN"
	envBaseURL     = "AMA_BASE_URL"
	envWorkspaceID = "AMA_WORKSPACE_ID"
	// envSessionID is the current session (= Ark session) id, used to build /api/runs/{id}/ark/...,
	// the group of pass-through APIs that resolve Ark credentials by session (list/attach session
	// files, thread events, and so on).
	envSessionID = "AMA_SESSION_ID"

	// defaultBaseURL is the address used when AMA_BASE_URL is not given: the default port of a local
	// amad. In the container amad always injects AMA_BASE_URL; this default only applies when using
	// the CLI by hand locally.
	defaultBaseURL = "http://localhost:9999"
)

// httpTimeout is the limit for a single request.
//
// ⚠️ It must be **clearly shorter** than the bash tool's timeout in the container (120 seconds),
// otherwise the whole tool call gets cut off while the CLI is still waiting; the agent then sees
// "command timed out", which does not point at "we were waiting on a slow request" at all. And tool
// calls are **serial**, so one stuck call drags down its sibling calls in the same batch.
const httpTimeout = 25 * time.Second

func main() {
	if err := run(os.Args[1:]); err != nil {
		// Errors always go to stderr, with a **non-zero exit code**.
		//
		// The agent judges success by the exit code; writing a failure to stdout and exiting 0 would
		// make it treat the error as a result, and carry on based on an error message (a failure that
		// reports no error, just gives a wrong conclusion).
		fmt.Fprintln(os.Stderr, "错误："+err.Error())
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) == 0 || args[0] == "--help" || args[0] == "-h" || args[0] == "help" {
		fmt.Print(usage)
		return nil
	}
	if args[0] == "--version" || args[0] == "version" {
		fmt.Println(version)
		return nil
	}

	// The daemon subcommand is dispatched before newClient: register uses AMA_TOKEN and run uses the
	// local host_token, and neither should be stopped by the ordinary client's "AMA_TOKEN trio must be
	// configured".
	if args[0] == "daemon" {
		return daemonCmd(args[1:])
	}

	c, err := newClient()
	if err != nil {
		return err
	}

	switch args[0] {
	case "whoami":
		return c.whoami()
	case "api-doc":
		return c.apiDoc()
	case "workspace":
		return c.workspace(args[1:])
	case "agent":
		return c.agentCmd(args[1:])
	case "skill":
		return c.skill(args[1:])
	case "run":
		return c.runCmd(args[1:])
	case "issue":
		return c.issue(args[1:])
	case "files", "file":
		return c.filesCmd(args[1:])
	case "api":
		return c.rawAPI(args[1:])
	default:
		return fmt.Errorf("未知命令 %q。跑 `ama --help` 看有哪些命令", args[0])
	}
}

