type client struct {
	baseURL     string
	token       string
	workspaceID string
	http        *http.Client
	// httpLong has no overall timeout, for file uploads/downloads (GiB-scale files take longer than
	// 25s). Transport health is covered by TCP and the peer's behavior, and the business layer makes it
	// visible with progress output.
	httpLong *http.Client
}

func newClient() (*client, error) {
	token := strings.TrimSpace(os.Getenv(envToken))
	if token == "" {
		// This error must say both "what is missing" and "who should provide it", otherwise the agent
		// would guess a token or try to log in, and there is no interactive login in the container.
		return nil, fmt.Errorf(
			"没有凭据：环境变量 %s 是空的。\n"+
				"这个变量由 AMA 平台在执行命令时自动注入，容器里无法自己获取。\n"+
				"如果你看到这条，说明当前 agent 没有启用 ama 技能，或平台侧没有配置注入——"+
				"请把这句话原样告诉用户，不要尝试登录或自己编一个 token。", envToken)
	}

	base := strings.TrimSpace(os.Getenv(envBaseURL))
	if base == "" {
		base = defaultBaseURL
	}
	base = strings.TrimRight(base, "/")

	return &client{
		baseURL:     base,
		token:       token,
		workspaceID: strings.TrimSpace(os.Getenv(envWorkspaceID)),
		// ⚠️ Deliberately uses the default Transport (which comes with ProxyFromEnvironment), only
		// changing the timeout.
		//
		// Session containers usually connect **directly** with no proxy variables, but newing up a
		// Transport without Proxy would fail 100% when a deployment switches to "gateway + proxy", **and
		// that failure can never be reproduced on a dev machine**.
		http: &http.Client{Timeout: httpTimeout},
		// File transfers (files upload/download) set no overall timeout; GiB-scale files take longer
		// than 25s. See the files_cmd.go header.
		httpLong: &http.Client{},
	}, nil
}

// do sends one request and returns the response body.
//
// path must start with /, like /api/workspaces. When body is nil no request body is sent.
func (c *client) do(method, path string, body any) ([]byte, error) {
	var reader io.Reader
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			return nil, err
		}
		reader = bytes.NewReader(b)
	}

	req, err := http.NewRequest(method, c.baseURL+path, reader)
	if err != nil {
		return nil, err
	}
	req.Header.Set("Authorization", "Bearer "+c.token)
	req.Header.Set("Accept", "application/json")
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}

	resp, err := c.http.Do(req)
	if err != nil {
		// A network-level failure must be clearly separated from "the server refused": the former
		// should be retried, the latter gives the same result after ten thousand retries. Mixing them
		// would make the agent keep retrying at a 403.
		return nil, fmt.Errorf("连不上 AMA（%s）：%w\n这是网络问题，不是权限问题", c.baseURL, err)
	}
	defer resp.Body.Close()

	raw, err := io.ReadAll(io.LimitReader(resp.Body, maxResponseBytes))
	if err != nil {
		return nil, err
	}

	if resp.StatusCode >= 400 {
		return nil, describeHTTPError(resp.StatusCode, raw)
	}
	return raw, nil
}

// maxResponseBytes keeps one huge response from flooding the agent's context.
//
// openapi.json alone is 284 KB, and the agent's context is limited. Truncating the rest is more
// useful than having it read screens of JSON.
const maxResponseBytes = 1 << 20

// doStream sends a request with a **streaming binary body** (file upload: whole object or a part).
//
// Differences from do: the body is an io.Reader + an explicit length instead of JSON; it uses
// httpLong with no overall timeout; the response is still read as JSON/envelope (upload APIs return a
// UserFile / a small 200 response for parts), with no special handling beyond the 1 MiB truncation.
//
// ⚠️ size must equal the number of bytes actually readable from content: the server forwards the part
// to storage by Content-Length, and if it is wrong it will truncate or hang (the same requirement as
// on the server side).
func (c *client) doStream(method, path, contentType string, content io.Reader, size int64) ([]byte, error) {
	req, err := http.NewRequest(method, c.baseURL+path, content)
	if err != nil {
		return nil, err
	}
	req.Header.Set("Authorization", "Bearer "+c.token)
	req.Header.Set("Accept", "application/json")
	req.Header.Set("Content-Type", contentType)
	req.ContentLength = size

	resp, err := c.httpLong.Do(req)
	if err != nil {
		return nil, fmt.Errorf("连不上 AMA（%s）：%w\n这是网络问题，不是权限问题", c.baseURL, err)
	}
	defer resp.Body.Close()

	raw, err := io.ReadAll(io.LimitReader(resp.Body, maxResponseBytes))
	if err != nil {
		return nil, err
	}
	if resp.StatusCode >= 400 {
		return nil, describeHTTPError(resp.StatusCode, raw)
	}
	return raw, nil
}

// describeHTTPError translates amad's error envelope into "what the agent should do".
//
// ⚠️ **The check is `code`, not the status code** (the spec says so explicitly): when a route is
// wrong, the standard library's 404 is text/plain, and judging by status code would call "the route
// is mounted wrong" "the resource does not exist".
//
// Every case must state the **next action**, because the most expensive failure mode is the agent
// getting "403 Forbidden" and then retrying with different parameters; that never succeeds and only
// burns a few rounds of tool calls.
func describeHTTPError(status int, raw []byte) error {
	var env struct {
		Code    string `json:"code"`
		Message string `json:"message"`
	}
	_ = json.Unmarshal(raw, &env)

	hint := ""
	switch env.Code {
	case "unauthenticated":
		hint = "凭据无效或已过期。**不要重试、也不要尝试登录**——" +
			"这把凭据由平台注入，容器里换不了。把这件事告诉用户。"
	case "access_denied":
		hint = "这个操作被拒。可能是：① 该操作不在 ama 技能允许的范围内（平台侧限制，" +
			"**换参数重试没有用**）；② 你不是这个空间的成员，或角色不够。" +
			"不要反复重试，把原因告诉用户。"
	case "not_found":
		hint = "资源不存在（注意：不是没权限）。先用对应的 list 命令确认 id 是否正确，" +
			"别自己拼 id。"
	case "invalid_argument":
		hint = "参数不对。看上面 message 里具体说了哪个字段。"
	case "conflict":
		hint = "与现有数据冲突（比如重名）。换个值再试。"
	}

	msg := strings.TrimSpace(env.Message)
	if msg == "" {
		// Not the standard envelope (maybe answered by a gateway or reverse proxy); give a short piece as
		// is; then the body itself is the clue, and translating would hide it.
		msg = strings.TrimSpace(string(raw))
		if len(msg) > 300 {
			msg = msg[:300] + "…"
		}
		if msg == "" {
			msg = "（响应体是空的）"
		}
	}

	out := fmt.Sprintf("HTTP %d", status)
	if env.Code != "" {
		out += " [" + env.Code + "]"
	}
	out += "：" + msg
	if hint != "" {
		out += "\n→ " + hint
	}
	return errors.New(out)
}

// printJSON pretty-prints the response as is.
//
// **Fields are not reorganized**: the agent should get the API's real shape, so it can understand it
// per the schema in `api-doc`. Making up our own slimmed-down structure would make it learn two.
func printJSON(raw []byte) error {
	var v any
	if err := json.Unmarshal(raw, &v); err != nil {
		// Not JSON, so print it as is (for example some APIs return plain text)
		fmt.Println(string(raw))
		return nil
	}
	out, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	fmt.Println(string(out))
	return nil
}

