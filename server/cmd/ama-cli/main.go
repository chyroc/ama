// AMA CLI: installed into the session container, letting the agent operate the user's own AMA data
// with the injected credential.
//
// # How it knows who it is
//
// Everything comes from **environment variables**, sent by amad on every command execution
// (per-exec injection in `shared/infra/shelltools`; see `credential.go`):
//
//	AMA_TOKEN         the credential, put into Authorization: Bearer. **Required**
//	AMA_BASE_URL      service address, default http://localhost:9999
//	AMA_WORKSPACE_ID  the workspace of the current session, the default scope of most subcommands
//	AMA_SESSION_ID    the current session id (= Ark session id), used to build /api/runs/{id}/ark/...
//
// ⚠️ **The credential is only read from environment variables, never from command line arguments.**
// This is a hard rule, not style: command lines in the container go as is into the `tool_use` event
// → stored in RunEvent (**a permanent record**) → into the model context → pushed to the browser via
// SSE. Once `--token` were allowed, the agent "adding it in passing" just once would leave that
// credential in the database forever. env does not go into argv, `ps` cannot see it, shell history
// does not record it, and `shared/infra/shelltools/scrub.go` scrubs it from command output.
//
// # Why not generate a client from OpenAPI
//
// amad's spec (`GET /api/openapi.json`, no auth needed) is generated from `authz/matrix.go` and
// watched by a consistency test, so a client generated from it really would never drift. But
// generating a client covering 106 operations has two problems: once committed, reviews are all noise;
// more importantly, it would lure the agent into calling APIs that are bound to be rejected.
//
// So only a dozen frequent subcommands are hand-written here, plus an `ama api` escape hatch:
// **contract discovery is left to runtime** (`ama api-doc` forwards that spec). The escape hatch does
// not enlarge the attack surface: the real boundary is on the amad side (see below), whether the CLI
// blocks something or not.
//
// # 🔒 The security boundary is on the server, not here
//
// What runs in the container are commands generated by the agent, which has bash and read tools;
// **one `env` and it has AMA_TOKEN**. So "disabling dangerous commands in the CLI" is security
// theater: with the token it can curl directly and get around it. Real restrictions must be enforced
// by amad when it checks the credential.
//
// This program does only one security-related thing: **make dangerous operations require explicit
// confirmation** (see confirmFlag), meant to stop honest mistakes like "one model hallucination",
// not a malicious agent. The two must be kept apart, or one may mistakenly believe client-side
// blocking provides real protection.
package main

