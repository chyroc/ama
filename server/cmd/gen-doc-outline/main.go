// Command gen-doc-outline generates, from the json tags of Go types, a description of "which
// keys a doc column may have", for the table outline at the top of repository/schema/*.sql.
//
// # Why the source of truth is the Go type, not the data in the database
//
// The content of a doc column is always `json.Marshal(some Go struct)` (see marshalDoc in
// coredao), so the set of keys is decided by the **struct**, not by any one row.
//
// ⚠️ **Sampling the real database is the wrong approach**: a field with omitempty does not
// appear at all when its value is zero, so sampling misses it, and those fields are exactly
// part of the HTTP contract (for example createdBy/updatedBy of apimodel.Agent: older rows
// simply do not have that key; see that section in core/README.md).
// The other way round, the database may still hold old keys **already removed from the
// struct**, and sampling would treat them as live fields. The two errors point in opposite
// directions and both mislead the reader.
//
// # Use go/ast, not regular expressions
//
// Nested types ([]AgentEnv / map[string]string / *ModelConfig), anonymous embedding, and
// field declarations spanning several lines all break regular expressions. go/ast gives the
// field name, type and tag directly.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
)

// Boundary markers of the doc description block. The table outline generated by
// gen-schema-outline.py uses ┌/└; this block uses a different pair, so each generator owns
// its own block and neither overwrites the other.
const (
	docBegin = "-- ├── Keys of the doc column (jsonb)"
	docEnd   = "-- ┤"
)

// docType records "which Go type the doc column of a table corresponds to".
type docType struct {
	Table string
	File  string
	Type  string
	// Note is an extra warning to write into the .sql (the "key is there but the value cannot
	// be trusted" kind of trap).
	Note string
}

// Tables with a doc column → their Go type. **This list is maintained by hand**: a doc column
// is just jsonb, and who writes into it depends on the call sites, which cannot be derived.
// Add a line here when you add such a table.
//
// ⚠️ Only 10 tables really have a doc column. The others are flat tables whose fields were
// "pulled out into real columns"; each .sql explains why it does not use jsonb (all fields
// are scalars / user_onboarding needs a separate coalesce on each of two columns, etc.).
// **Do not invent a doc type for them.**
//
// ⚠️ run_events has a doc column but is **deliberately not in this list**: it stores an
// anonymous map (only three keys: type / sequence / session_thread_id), not
// apimodel.RunEvent, and it **has no read path** (run_events.sql says plainly that the read
// path does not deserialize it; the column exists only so people can grep it when debugging).
// Putting apimodel.RunEvent here would generate a description that looks right but is wrong.
//
// ⚠️ **workspaces used to be in this list and no longer is**: that column has been dropped
// (all five steps of "split doc" are done; see the end of workspaces.sql). After the column was
// dropped its doc-key description became a block **describing a column that does not exist**,
// which is worse than nothing, so it was removed together with that block in workspaces.sql.
// When another doc table goes through the same migration, add/remove its line here as well.
var docTypes = []docType{
	{Table: "agents", File: "model/apimodel/apimodel.go", Type: "Agent"},
	{Table: "skills", File: "model/apimodel/apimodel.go", Type: "Skill"},
	{Table: "runs", File: "model/apimodel/apimodel.go", Type: "Run"},
	{
		Table: "ark_secrets", File: "model/apimodel/apimodel.go", Type: "ArkSecret",
		Note: "⚠️ APIKey has **no json tag**, so the key name is `APIKey` (upper case), not `apiKey`;\n" +
			"⚠️ it is encrypted with cryptobox before it is stored (`v1:` prefix); the value in the\n" +
			"   database is ciphertext, not the key.",
	},
	{
		Table: "schedules", File: "model/apimodel/schedule.go", Type: "Schedule",
		// See store_pg_schedule.go: ClaimDueSchedules only updates the columns and does not rewrite doc.
		Note: "⚠️ doc.nextRunAt / doc.runNowRequested are **stale copies**; the real columns with the\n" +
			"   same names win. ClaimDueSchedules only updates the columns and does not rewrite doc:\n" +
			"   a read-modify-write on the blob would lose updates under concurrency.",
	},
	{Table: "ark_bindings", File: "model/persistmodel/persistmodel.go", Type: "ArkBinding"},
	{Table: "feishu_apps", File: "feishu/app.go", Type: "App"},
	{Table: "feishu_sessions", File: "feishu/app.go", Type: "Session"},
}

// field is one parsed json field.
type field struct {
	JSONName  string
	GoType    string
	OmitEmpty bool
	Doc       string
}

// parseStruct extracts the json fields of the struct named typeName in file.
func parseStruct(file, typeName string) ([]field, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var out []field
	var found bool
	ast.Inspect(f, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok || ts.Name.Name != typeName {
			return true
		}
		st, ok := ts.Type.(*ast.StructType)
		if !ok {
			return true
		}
		found = true
		for _, fld := range st.Fields.List {
			if len(fld.Names) == 0 || !fld.Names[0].IsExported() {
				continue // unexported fields do not go into JSON
			}
			// ⚠️ **Exported fields without a tag also go into JSON**, with the Go field name as the key.
			// apimodel.ArkSecret.APIKey is exactly that case (the key is `APIKey`, not `apiKey`).
			// Looking only at tags would miss it entirely, and it is the most important field of
			// that table.
			name, omit := fld.Names[0].Name, false
			if fld.Tag != nil {
				tag := reflect.StructTag(strings.Trim(fld.Tag.Value, "`"))
				jt := tag.Get("json")
				if jt == "-" {
					continue
				}
				if jt != "" {
					parts := strings.Split(jt, ",")
					if parts[0] != "" {
						name = parts[0]
					}
					for _, p := range parts[1:] {
						if p == "omitempty" {
							omit = true
						}
					}
				}
			}
			out = append(out, field{
				JSONName:  name,
				GoType:    typeString(fld.Type),
				OmitEmpty: omit,
			})
		}
		return false
	})
	if !found {
		return nil, fmt.Errorf("%s 里找不到类型 %s", file, typeName)
	}
	return out, nil
}

// typeString turns an AST type node back into its source form.
func typeString(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return "*" + typeString(t.X)
	case *ast.ArrayType:
		return "[]" + typeString(t.Elt)
	case *ast.MapType:
		return "map[" + typeString(t.Key) + "]" + typeString(t.Value)
	case *ast.SelectorExpr:
		return typeString(t.X) + "." + t.Sel.Name
	case *ast.InterfaceType:
		return "any"
	default:
		return "?"
	}
}

// block builds the comment block to insert into the .sql.
func block(dt docType, fields []field) string {
	wn := 0
	for _, f := range fields {
		if n := len(f.JSONName); n > wn {
			wn = n
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s (= json.Marshal(%s))\n", docBegin, dt.Type)
	fmt.Fprintf(&b, "-- │ ⚠️ This block is **generated from the json tags of the Go type**, not by sampling data\n")
	fmt.Fprintf(&b, "-- │    in the database. Keys with omitempty are absent when the value is zero, so sampling\n")
	fmt.Fprintf(&b, "-- │    always misses them, yet they are part of the contract. After changing the type, run:\n")
	fmt.Fprintf(&b, "-- │        cd server && go run ./cmd/gen-doc-outline -w\n")
	fmt.Fprintf(&b, "-- │    Source of truth: %s, type %s\n", dt.File, dt.Type)
	if dt.Note != "" {
		fmt.Fprintf(&b, "-- │\n")
		for _, ln := range strings.Split(dt.Note, "\n") {
			fmt.Fprintf(&b, "-- │ %s\n", ln)
		}
	}
	fmt.Fprintf(&b, "-- │\n")
	for _, f := range fields {
		suffix := ""
		if f.OmitEmpty {
			suffix = "   ← omitempty, the key may be missing entirely"
		}
		fmt.Fprintf(&b, "-- │ %-*s  %s%s\n", wn, f.JSONName, f.GoType, suffix)
	}
	fmt.Fprintf(&b, "%s\n", docEnd+strings.Repeat("─", 74))
	return b.String()
}

// apply inserts blk into the .sql: after the table outline (the └── line), before the body.
// Re-running is safe: an existing block is removed first.
func apply(path, blk string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	lines := strings.Split(string(raw), "\n")

	// Remove the old doc block
	var kept []string
	skipping := false
	for _, ln := range lines {
		if strings.HasPrefix(ln, docBegin) {
			skipping = true
			continue
		}
		if skipping {
			if strings.HasPrefix(ln, docEnd) {
				skipping = false
			}
			continue
		}
		kept = append(kept, ln)
	}

	// Find the end of the table outline (└──) and insert after it
	at := -1
	for i, ln := range kept {
		if strings.HasPrefix(ln, "-- └──") {
			at = i + 1
			break
		}
	}
	if at < 0 {
		return fmt.Errorf("%s 里找不到结构一览的结尾（先跑 scripts/gen-schema-outline.py）", path)
	}
	out := append([]string{}, kept[:at]...)
	out = append(out, strings.Split(strings.TrimRight(blk, "\n"), "\n")...)
	out = append(out, kept[at:]...)
	return os.WriteFile(path, []byte(strings.Join(out, "\n")), 0o644)
}

func main() {
	write := flag.Bool("w", false, "把生成的说明写进 repository/schema/*.sql")
	flag.Parse()

	sort.Slice(docTypes, func(i, j int) bool { return docTypes[i].Table < docTypes[j].Table })
	for _, dt := range docTypes {
		fields, err := parseStruct(dt.File, dt.Type)
		if err != nil {
			fmt.Fprintf(os.Stderr, "%s: %v\n", dt.Table, err)
			os.Exit(1)
		}
		blk := block(dt, fields)
		if !*write {
			fmt.Print(blk)
			continue
		}
		path := filepath.Join("repository/schema", dt.Table+".sql")
		if err := apply(path, blk); err != nil {
			fmt.Fprintf(os.Stderr, "写 %s 失败: %v\n", dt.Table, err)
			os.Exit(1)
		}
		fmt.Printf("已更新 %s（%d 个键）\n", path, len(fields))
	}
}
