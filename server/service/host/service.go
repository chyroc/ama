// Package host is the business domain of the "host executor": users register their own machines with the ama daemon,
// bind machines into workspaces, and the agent's tool calls run on that machine.
//
// # Boundaries (nobody may depend on anybody)
//
//   - This package depends on model/persistmodel and shared/hostproto, not on core / apihandler.
//   - Upstream terminal frames must be delivered back to the instance holding the browser connection, which is in-process state of core;
//     this is inverted through the narrow TermUpSink interface, injected by cmd/amad at wiring time; this package does not know core.
//   - Cross-instance wake-up (the in-process fan-out of PG NOTIFY) is injected through a narrow Waiter interface with the same shape as
//     core.HostWakes (WaitForDispatch), again without importing core.
//   - The HTTP layer is in apihandler; host_token bare-mux auth is done there, and this package only provides
//     AuthenticateToken for it to call.
//
// # Key sequences
//
//	register:  user AMA_TOKEN → Register idempotently upserts the hosts row, issuing a random host_token the first time
//	heartbeat: host_token → TouchHost renews + ClaimPending long polling (≤20s)
//	exec:      core tool layer → Exec (pre-check online/GNU tools → into host_dispatches → wait for the result)
//	result:    daemon → SubmitResults (exec CAS into the database / terminal frames straight to the sink)
//	offline:   core.HostWatcher → SweepOfflineHosts (CAS to offline + fail pending)
package host

import (
	"context"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"log/slog"
	"strings"
	"time"

	"github.com/chyroc/ama/server/model/persistmodel"
	"github.com/chyroc/ama/server/shared/hostproto"
)

// Host online grace: last_seen_at within this long counts as online. It must be ≥ twice the longest heartbeat interval
// (20s long polling + network jitter), and match core.HostWatcher's offline threshold exactly.
const onlineGrace = 90 * time.Second

// Status literals (no enum; the same across the repo).
const (
	StatusOnline  = "online"
	StatusOffline = "offline"
)

// Public ID prefixes (an observable contract; see the comment on core.nextID).
const (
	idPrefixHost = "hst"
	idPrefixBind = "wsh"
	idPrefixCall = "htc"
)

// maxHostsPerUser is the maximum number of hosts one user may register, guarding against mistakes/scripts creating rows without end.
// 20 covers the normal need of "one Mac + one Linux box + a few dev/test machines"; beyond that we
// guide users to revoke old machines in global settings, instead of silently rejecting.
const maxHostsPerUser = 20

// ErrNotFound / ErrConflict are business-layer errors; the HTTP layer turns them into 404/409.
//
// ⚠️ They must wrap the persistmodel sentinels of the same name: apihandler.h.fail only recognizes
// persistmodel.ErrNotFound and the like; a home-made bare error falls into default 500, so cases expected to be 404 like owner mismatch
// or machine not found would be treated as internal server failures.
var (
	ErrNotFound = fmt.Errorf("host: 不存在: %w", persistmodel.ErrNotFound)
	ErrConflict = fmt.Errorf("host: 冲突: %w", persistmodel.ErrConflict)
)

// Waiter is the in-process waiting point of cross-instance wake-up (core.HostWakes satisfies it).
type Waiter interface {
	Wait(ctx context.Context, hostID string) <-chan struct{}
}

// TermUpSink delivers terminal frames reported by the daemon to the instance holding the browser terminal connection.
//
// Implementation side (core): if this instance holds the connection for that terminalID it writes directly, otherwise it relays through pgmq
// topic term:<terminalID> to the holding instance. terminalID is generated by core and sent down with
// term_open; the daemon brings it back as is.
type TermUpSink interface {
	// DeliverTermFrame delivers one frame. data is for closed/error text; dataB64 is for
	// the raw PTY bytes of output frames (standard base64); which one is used depends on frameType.
	// Output frames must pass b64 through to the browser **as is** (atob on the browser side), never decoded
	// into a Go string in between and json.Marshal'ed again: that triggers UTF-8 validation and replaces invalid bytes with �.
	DeliverTermFrame(ctx context.Context, terminalID, frameType, data, dataB64 string) error
}

// Service is the host domain service. Store is required; Waiter/Sink/Leases degrade when the matching feature is empty
// (without Waiter, long polling and Exec use plain tickers; without Sink, terminal frames are dropped, counted and logged).
type Service struct {
	store          Store
	wait           Waiter
	sink           TermUpSink
	resultScrubber ExecResultScrubber
	// toolResultScrubber scrubs native KindTool result text, using the same credential source as resultScrubber.
	toolResultScrubber ToolResultScrubber
	log                *slog.Logger
	streams            *streamRegistry
}

// Config wires up Service.
// ExecResultScrubber removes plaintext secrets from stdout/stderr before exec results are stored.
// sessionID is the Ark session (== run id); the implementation (core) uses the credentials injected for that session
// to decide which values to scrub. Returns the scrubbed result. May be empty: with no credential source installed, nothing is scrubbed (and there are no secrets to scrub).
type ExecResultScrubber func(ctx context.Context, sessionID string, res hostproto.ExecResult) hostproto.ExecResult

type Config struct {
	Store          Store
	Wait           Waiter
	Sink           TermUpSink
	ResultScrubber ExecResultScrubber
	Log            *slog.Logger
}

// New builds Service.
func New(cfg Config) (*Service, error) {
	if cfg.Store == nil {
		return nil, errors.New("host: Store 不能为 nil")
	}
	log := cfg.Log
	if log == nil {
		log = slog.Default()
	}
	return &Service{
		store:          cfg.Store,
		wait:           cfg.Wait,
		sink:           cfg.Sink,
		resultScrubber: cfg.ResultScrubber,
		log:            log,
		streams:        newStreamRegistry(),
	}, nil
}

// newID generates a random ID with no central coordination (prefix_32hex). The host domain is written by multiple instances, so an in-process counter cannot be used
// (the repo's distributed-service rule); collisions of 16 random bytes are negligible; same approach as auth API Keys.
func newID(prefix string) string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		// crypto/rand only fails when the system entropy source is unavailable; continuing would leave no safe ID to issue.
		panic(fmt.Sprintf("host: 读系统随机数失败: %v", err))
	}
	return prefix + "_" + hex.EncodeToString(b[:])
}

func hashToken(token string) string {
	sum := sha256.Sum256([]byte(token))
	return hex.EncodeToString(sum[:])
}

func newToken() string {
	var b [32]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic(fmt.Sprintf("host: 读系统随机数失败: %v", err))
	}
	return hex.EncodeToString(b[:])
}

// Register idempotently registers one host. ownerEmail is the email the HTTP layer took from the auth context;
// a self-claimed value in the body is not accepted.
//
// The first time (no row for the same owner+uuid) it generates a random host_token; the plaintext is returned only in this response, and the database stores
// its sha256; later registrations (daemon restart/upgrade) hit the existing row, **only refresh the registration snapshot fields
// (name/os/arch/version/GNU probe), and do not re-issue the token**; the returned token is empty.
func (s *Service) Register(
	ctx context.Context, ownerEmail string, req hostproto.RegisterRequest, now time.Time,
) (hostproto.RegisterResponse, error) {
	ownerEmail = strings.ToLower(strings.TrimSpace(ownerEmail))
	if ownerEmail == "" {
		return hostproto.RegisterResponse{}, errors.New("host: 注册缺少属主身份")
	}
	req.Name = strings.TrimSpace(req.Name)
	// HostUUID is part of the (owner, uuid) unique key: an empty string would wrongly collapse several machines of the same owner
	// into one row (a new machine overwriting the old machine's snapshot, mixed-up result ownership). The daemon generates a non-empty UUID
	// with crypto/rand; this blocks unexpected empty/blank requests.
	if strings.TrimSpace(req.HostUUID) == "" {
		return hostproto.RegisterResponse{}, errors.New("host: 注册缺少 host UUID")
	}

	// Quota: only checked when "this is confirmed to be a new host". Idempotent re-registration with the same uuid (daemon restart/upgrade)
	// passes directly without the quota; this also avoids a user's machine never being able to register again after reinstalling the daemon.
	existing, err := s.store.GetHostByOwnerUUID(ctx, ownerEmail, req.HostUUID)
	isNew := errors.Is(err, ErrNotFound) || errors.Is(err, persistmodel.ErrNotFound)
	if err != nil && !isNew {
		return hostproto.RegisterResponse{}, fmt.Errorf("host: 注册前查询宿主机失败: %w", err)
	}
	if isNew {
		owned, err := s.store.ListHostsByOwner(ctx, ownerEmail)
		if err != nil {
			return hostproto.RegisterResponse{}, fmt.Errorf("host: 注册前统计宿主机数失败: %w", err)
		}
		if len(owned) >= maxHostsPerUser {
			return hostproto.RegisterResponse{}, fmt.Errorf(
				"host: 每个用户最多注册 %d 台宿主机，当前已有 %d 台；请先在全局设置「宿主机」里吊销不再使用的机器: %w",
				maxHostsPerUser, len(owned), persistmodel.ErrInvalidArgument)
		}
	}
	_ = existing // The row content is not used, only "exists or not"; the real idempotent hit is returned by Upsert.

	token := newToken()
	row := persistmodel.Host{
		ID:         newID(idPrefixHost),
		OwnerEmail: ownerEmail,
		Name:       req.Name,
		OS:         req.OS,
		Arch:       req.Arch,
		HostUUID:   req.HostUUID,
		// A new row stores our hash; on conflict the Store keeps the existing hash (the token is not rotated).
		TokenHash:     hashToken(token),
		Status:        StatusOffline,
		DaemonVersion: req.DaemonVersion,
		GNUToolsOK:    req.GNUToolsOK,
		Toolcheck:     req.ToolCheck,
		NativeTools:   req.NativeTools,
		CreatedAt:     now,
	}
	// inserted=true means this call really created the row (the Store decides by whether the returned row's TokenHash
	// equals the one we submitted; on conflict it updates the snapshot but not token_hash).
	saved, inserted, err := s.store.UpsertRegisteredHost(ctx, row)
	if err != nil {
		return hostproto.RegisterResponse{}, fmt.Errorf("host: 注册宿主机失败: %w", err)
	}
	if !inserted {
		return hostproto.RegisterResponse{HostID: saved.ID, AlreadyRegistered: true}, nil
	}
	return hostproto.RegisterResponse{HostID: saved.ID, Token: token}, nil
}

// ListMyHosts lists all hosts registered by the owner (used by the global settings page).
func (s *Service) ListMyHosts(ctx context.Context, ownerEmail string) ([]persistmodel.Host, error) {
	return s.store.ListHostsByOwner(ctx, strings.ToLower(strings.TrimSpace(ownerEmail)))
}

// DeleteHost revokes a host: owner only.
//
// Deleting the row cascades to workspace_hosts (DDL on delete cascade); in-flight exec
// dispatches are not child rows of hosts (deliberately a soft reference), and the HostWatcher would only settle them in its next round
// by some way other than "row not found", so here the pending execs are failed explicitly,
// so the agent does not wait for 130s for nothing. The daemon's next heartbeat/result gets 401 and wipes its local token.
func (s *Service) DeleteHost(ctx context.Context, ownerEmail, hostID string) error {
	ownerEmail = strings.ToLower(strings.TrimSpace(ownerEmail))
	h, err := s.store.GetHost(ctx, hostID)
	if err != nil {
		return err
	}
	if h.OwnerEmail != ownerEmail {
		// Do not admit it exists, to avoid leaking "this machine exists but is not yours" (404, not 403).
		return ErrNotFound
	}
	failMsg := "宿主机已被属主吊销"
	if n, err := s.store.FailPendingExecsForHost(ctx, hostID,
		string(hostproto.FailedExecResult(hostproto.ExecErrHostOffline, failMsg)), time.Now()); err != nil {
		return fmt.Errorf("host: 吊销前失败在途调用出错: %w", err)
	} else if n > 0 {
		s.log.Info("吊销宿主机，已失败在途工具调用", slog.String("host", hostID), slog.Int64("calls", n))
	}
	if err := s.store.DeleteHost(ctx, hostID); err != nil {
		return fmt.Errorf("host: 吊销宿主机失败: %w", err)
	}
	return nil
}

// AuthenticateToken authenticates the heartbeat/result routes on the bare mux: plaintext host_token → host row.
// Not found always becomes 401 in the HTTP layer (here there is no distinction between "bad format" and "revoked").
func (s *Service) AuthenticateToken(ctx context.Context, token string) (persistmodel.Host, error) {
	token = strings.TrimSpace(token)
	if token == "" {
		return persistmodel.Host{}, ErrNotFound
	}
	return s.store.GetHostByTokenHash(ctx, hashToken(token))
}

// BindHost binds the owner's own machine into a workspace.
//
// v1 hard rule: **you can only bind hosts you own** (even a workspace owner/admin cannot bind on behalf of someone else).
// Workspace ownership / ActionManage permission is already checked in the HTTP + authz layer; here we only check the host owner.
// Idempotent: a repeated bind returns nil (the unique index covers concurrent TOCTOU; the Go layer gives a readable error first).
func (s *Service) BindHost(ctx context.Context, actorEmail, workspaceID, hostID string, now time.Time) error {
	actorEmail = strings.ToLower(strings.TrimSpace(actorEmail))
	h, err := s.store.GetHost(ctx, hostID)
	if err != nil {
		return err
	}
	if h.OwnerEmail != actorEmail {
		// Same as DeleteHost: do not admit it exists.
		return ErrNotFound
	}
	bind := persistmodel.WorkspaceHost{
		ID:          newID(idPrefixBind),
		WorkspaceID: workspaceID,
		HostID:      hostID,
		AddedBy:     actorEmail,
		CreatedAt:   now,
	}
	if err := s.store.BindWorkspaceHost(ctx, bind); err != nil {
		return fmt.Errorf("host: 绑定宿主机到空间失败: %w", err)
	}
	return nil
}

// ListWorkspaceHosts lists the hosts bound to a workspace (join hosts + binding rows, with online status,
// registrant and binder).
func (s *Service) ListWorkspaceHosts(ctx context.Context, workspaceID string) ([]persistmodel.BoundHost, error) {
	return s.store.ListWorkspaceHosts(ctx, workspaceID)
}

// UnbindHost removes a machine from a workspace. **Unbinding only requires workspace manage permission (checked in the HTTP layer),
// not being the host owner**: admins must be able to remove machines that others bound earlier.
func (s *Service) UnbindHost(ctx context.Context, workspaceID, hostID string) error {
	if err := s.store.UnbindWorkspaceHost(ctx, workspaceID, hostID); err != nil {
		return fmt.Errorf("host: 解绑宿主机失败: %w", err)
	}
	return nil
}

// ResolveBoundHost is for validating "workspace assignment": hostID must exist and already be bound to the workspace.
// It does not check the host owner: in the two-level model a workspace admin can assign machines bound by others to an agent;
// "is the current user allowed to make this assignment" is decided by the agent save gate by role + owner
// (service/agent.ensureExecutorAllowed). Not found / not bound both return ErrNotFound,
// without telling the caller which.
func (s *Service) ResolveBoundHost(
	ctx context.Context, workspaceID, hostID string,
) (persistmodel.Host, error) {
	h, err := s.store.GetHost(ctx, hostID)
	if err != nil {
		return persistmodel.Host{}, err
	}
	if _, err := s.store.GetWorkspaceHost(ctx, workspaceID, hostID); err != nil {
		return persistmodel.Host{}, err
	}
	return h, nil
}

// ResolvePersonalHost is for validating "personal direct connection": hostID must exist and its owner must be actor
// themselves. Personal direct connection does not go through workspace_hosts, so only hosts is checked here.
// Not found / not your machine both return ErrNotFound (do not admit the host exists, to avoid id probing).
func (s *Service) ResolvePersonalHost(
	ctx context.Context, actorEmail, hostID string,
) (persistmodel.Host, error) {
	h, err := s.store.GetHost(ctx, hostID)
	if err != nil {
		return persistmodel.Host{}, err
	}
	if h.OwnerEmail != strings.ToLower(strings.TrimSpace(actorEmail)) {
		return persistmodel.Host{}, ErrNotFound
	}
	return h, nil
}

// GetHost exports getting a host by id (for terminal tickets checking the owner, and read-path diagnostics).
func (s *Service) GetHost(ctx context.Context, hostID string) (persistmodel.Host, error) {
	return s.store.GetHost(ctx, hostID)
}

// HostExists reports whether the host row still exists. Used to re-check "personal direct connection" when creating a session:
// a personal machine does not become invalid through workspace unbinding; the only invalidating event is the owner revoking it (DELETE hosts).
// When the storage layer returns ErrNotFound it gives (false, nil); other errors go up, and the caller decides how to degrade.
func (s *Service) HostExists(ctx context.Context, hostID string) (bool, error) {
	if _, err := s.store.GetHost(ctx, hostID); err != nil {
		if isHostNotFound(err) {
			return false, nil
		}
		return false, err
	}
	return true, nil
}

// HostOwnerEmail returns the host owner's lowercase email; terminal tickets use it for the tier "only the owner can open a terminal on a personal direct connection".
func (s *Service) HostOwnerEmail(ctx context.Context, hostID string) (string, error) {
	h, err := s.store.GetHost(ctx, hostID)
	if err != nil {
		return "", err
	}
	return h.OwnerEmail, nil
}

// SetTermSink injects the relay exit for upstream terminal frames.
//
// Why a setter instead of a required constructor argument: the host service must be created before core.Service
// (agent domain save validation depends on it), while the terminal relay exit is provided by core.Service (it needs the in-process
// terminalHub and pgmq): the wiring has an order, so leave an opening for the wiring side to fill in after core is built.
// Until then terminal frames are dropped and logged (Exec/heartbeats do not depend on it).
func (s *Service) SetTermSink(sink TermUpSink) { s.sink = sink }

// SetResultScrubber injects the result scrubber after Service is constructed (at wiring time coreSvc is built later than hostSvc,
// so it cannot go through Config). It must be called before the service starts taking traffic.
func (s *Service) SetResultScrubber(f ExecResultScrubber) { s.resultScrubber = f }

// SetToolResultScrubber injects the scrubber for native KindTool results, at the same time and with the same credential source as
// SetResultScrubber.
func (s *Service) SetToolResultScrubber(f ToolResultScrubber) { s.toolResultScrubber = f }
