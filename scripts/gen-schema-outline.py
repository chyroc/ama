#!/usr/bin/env python3
"""Generate or update a "table outline" comment block at the top of every .sql file.

⚠️ **The source of truth is a real database, not the text of the .sql files.** The shape is
read from the catalog of a schema that was really created. See schemalib.py for why.

⚠️ **The schema is rebuilt every time** (see schemalib.py): reading a long-lived schema goes
stale silently. You change the DDL, run this script, and the outline still shows the old
types, while the script exits normally and reports nothing.

Which container / database to use can be overridden with environment variables; see
"Which database" in schemalib.py.
"""
from pathlib import Path

import schemalib as lib

BEGIN = '-- ┌── Table outline'
END = '-- └──'


def width(s):
    """Count wide (CJK) characters as two columns, otherwise columns do not line up."""
    return sum(2 if ord(ch) > 0x2000 else 1 for ch in s)


def pad(s, n):
    return s + ' ' * max(0, n - width(s))


def outline(table):
    cols = lib.columns(table)
    idxs = lib.indexes(table)
    wn = max([width(c[0]) for c in cols] + [4])
    wt = max([width(c[1]) for c in cols] + [4])

    lines = [f'{BEGIN}: {table} ' + '─' * max(0, 53 - width(table))]
    lines.append('-- │ ⚠️ This block is **generated from the catalog of a real database**, not written by')
    lines.append('-- │    hand. The shape the DDL below actually creates is what counts. After changing')
    lines.append('-- │    the DDL, run:')
    lines.append('-- │        python3 scripts/gen-schema-outline.py')
    lines.append('-- │')
    for name, typ, notnull, dflt, _ident in cols:
        extra = 'not null' if notnull else ''
        if dflt.startswith('nextval('):
            extra = (extra + ' ' if extra else '') + '(sequence)'
        elif dflt:
            extra = (extra + ' ' if extra else '') + f'default {dflt}'
        lines.append(f'-- │ {pad(name, wn)}  {pad(typ, wt)}  {extra}'.rstrip())
    lines.append('-- │')
    for name, isprimary, isunique, ddl in idxs:
        kind = 'primary key' if isprimary == 't' else ('unique' if isunique == 't' else 'index')
        cols_part = ddl[ddl.index(' USING ') + 7:]
        cols_part = cols_part[cols_part.index('('):] if '(' in cols_part else cols_part
        lines.append(f'-- │ {kind} {name}')
        lines.append(f'-- │      {cols_part}')
    lines.append(END + '─' * 74)
    return '\n'.join(lines)


def apply(path, table):
    text = Path(path).read_text()
    body = text.split('\n')
    # Remove the old outline (so re-running gives the same result)
    if body and body[0].startswith(BEGIN):
        for i, ln in enumerate(body):
            if ln.startswith(END):
                body = body[i + 1:]
                while body and body[0].strip() == '':
                    body.pop(0)
                break
    # The doc-key block right after it (generated by gen-doc-outline, starts with `-- ├──`)
    # sticks to this block with no blank line in between.
    sep = '\n' if body and body[0].startswith('-- ├──') else '\n\n'
    Path(path).write_text(outline(table) + sep + '\n'.join(body))


if __name__ == '__main__':
    names = lib.rebuild()
    try:
        for name in names:
            apply(lib.SCHEMA_DIR / name, name[:-4])
        print(f'已更新 {len(names)} 份 .sql 的表结构一览')
    finally:
        lib.drop()
