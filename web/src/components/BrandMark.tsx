/**
 * Brand mark: a dark purple base + three color blocks forming a cube shape.
 *
 * # Why inline SVG instead of <img src="/favicon.svg">
 *
 * Three reasons; only the first is hard:
 *
 * 1. **Things in `web/public/` go through an HTTP request, and the brand spot is above the fold**. With <img> the logo arrives one RTT
 *    after the page skeleton, showing as a blank flash on first paint, and the landing page's mark is in the most visible spot.
 *    Inlining it into the JS bundle removes that window.
 * 2. The paths are only ~4 KB, and this component is on every page; not worth a separate request.
 * 3. Only inlining lets the base's rounding follow the repo's r-chip (see below).
 *
 * The favicon files must still stay in public/: browsers only accept static files at the root path,
 * which is a different path. Both shapes are generated by the same script, so they do not drift.
 *
 * # Rounding and the dark-mode ring
 *
 * The source is a **full-bleed square** (all four corners dark purple); rounding is added by the display layer: here it uses the repo's existing `r-chip`
 * (6px, see the four radius levels in docs/guides/styling.md), so the brand spot's rounding is on the same scale as other
 * small squares in the UI, and changing the scale does not require touching this file.
 *
 * In dark mode there is an extra `ring-1 ring-border`, for a calculated reason: the logo base #3C043C against the dark page background
 * (--background around #161719) has a contrast of only **1.04:1**, so the edge is effectively gone and the logo blurs into
 * a dark spot on the page; the light page background is 15.8:1 and needs no ring at all. **Do not use dark: variants**:
 * the repo does not use them anywhere; light/dark switch only through semantic tokens (`--border` has a value in each theme),
 * so writing `ring-border` here automatically gives "almost invisible on light, just enough to outline on dark".
 *
 * ring instead of border: border takes part in the box model and would stretch size-9 to 38px,
 * and both places that use this component align with the text baseline in a flex row: **that 1px would make the whole row jitter**.
 * ring is drawn outside the box and takes no layout space.
 */

import { BRAND_COLORS, BRAND_PATHS, BRAND_VIEWBOX } from "@/components/brandPaths";

export function BrandMark({
  className = "size-9",
  title,
}: {
  /** Size and extra styles. Default size-9, the same size as the accent square the landing page had before. */
  className?: string;
  /**
   * Name for screen readers. **Not given by default**: both places that use it have the "AMA" wordmark or the workspace name right next to it;
   * reading it again is repetition, so by default it renders as a decorative graphic (aria-hidden).
   * Pass it only when the logo appears alone with no adjacent text.
   */
  title?: string;
}) {
  return (
    <svg
      viewBox={`0 0 ${BRAND_VIEWBOX} ${BRAND_VIEWBOX}`}
      className={`${className} shrink-0 r-chip ring-1 ring-border`}
      // Only with a title is it an "image"; otherwise it is decoration: screen readers should skip it, not read "AMA AMA".
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      data-testid="brand-mark"
    >
      {title ? <title>{title}</title> : null}
      {/*
        The base fills the viewBox; rounding is left to CSS r-chip, no rx here. Writing it would mean "one
        radius in the SVG, another in CSS", and changing the scale would surely miss one.

        **This depends on "className being on the <svg> itself"**: the svg root element has the UA default
        `overflow:hidden`, so border-radius really clips the canvas content. Moved to an outer div it
        **no longer clips** (tested: in a div with only border-radius, the square corners still show), and then you must
        add overflow-hidden too. So do not move these classes outward.
      */}
      <rect width={BRAND_VIEWBOX} height={BRAND_VIEWBOX} fill={BRAND_COLORS.plate} />
      <path d={BRAND_PATHS.cream} fill={BRAND_COLORS.cream} />
      <path d={BRAND_PATHS.red} fill={BRAND_COLORS.red} />
      <path d={BRAND_PATHS.yellow} fill={BRAND_COLORS.yellow} />
    </svg>
  );
}
