/**
 * The collection side of problem feedback: turns "what just went wrong" into a payload that can be
 * reported.
 *
 * # Why the collection logic is here and not in components
 *
 * Reporting has two triggers, with exactly the same shape but different timing:
 *
 *   first level   sent **automatically** when a failure happens (the user clicked nothing): read
 *                 failures in useAsyncData's catch,
 *                 write failures in useWriteError's setError. Both call reportAutoFeedback.
 *                 **Long-lived connection failures take a third path** (reportConnectionFailure);
 *                 see below for why.
 *   second level  a button where the error is shown, sent only when the user clicks: the
 *                 full-block error state is AsyncErrorBlock,
 *                 the one-line inline one is InlineError.
 *
 * Both share one collection function, so "what first level collects, what second level collects"
 * is defined in only one place.
 * With a copy on each side they would drift sooner or later, and the drift always goes **first
 * level quietly collecting more**;
 * that is the one mistake this feature must never make.
 *
 * # ⚠️ Long-lived connections (SSE / WebSocket) are not on the two paths above
 *
 * `useAsyncData` and `useWriteError` cover **requests made with fetch**. SSE and
 * WebSocket go through neither, and have no "rejected Promise" to classify, so their failures
 * **are never recorded at all**, with zero errors: all the code is there, tests green, it is just
 * never triggered.
 * This is the same kind of gap as "first level only covered read failures", except this time a
 * whole kind of connection was missed.
 * See reportConnectionFailure.
 *
 * # ⚠️ The boundary between first and second level (read before changing this file)
 *
 * | Field | First | Second | Why |
 * | --- | --- | --- | --- |
 * | Route pattern (ids removed) | ✅ | ✅ | Low cardinality; can aggregate "which page errors most" |
 * | HTTP status / error code / category | ✅ | ✅ | Core of diagnosis, and contains nobody's data |
 * | Error text | ✅ | ✅ | A Chinese sentence from the backend, not user input |
 * | Browser / OS summary | ✅ | ✅ | "Only happens on Safari" is a real cause |
 * | Frontend version | ✅ | ✅ | "Which version introduced it" |
 * | **Server logid** | ✅ | ✅ | See the section below: it needs no user consent |
 * | **Full path (with ids)** | ❌ | ✅ | Can pinpoint a specific conversation; first level has no user consent |
 * | **Current agent** | ❌ | ✅ | Same as above |
 * | **Recent API calls** | ❌ | ✅ | Could rebuild what this person was just doing |
 * | **Console errors** | ❌ | ✅ | May contain stacks and variable values |
 * | token / cookie / response body / message text | ❌ | ❌ | **Never collected at either level**; see below |
 *
 * The last row does not rely on discipline here: **the backend struct simply has no such fields**
 * (FeedbackInput in server/core/feedback.go), so they would be dropped even if sent.
 * One less send here, one less receive there; both guards are in place.
 *
 * # Why logid is collected at both levels
 *
 * It needs no user consent: the string is **generated by our own server** (withLogID in httpd),
 * contains none of the user's input, and is not a credential; `shared/infra/secret` even names it
 * when deliberately not masking bare hex:
 * "logid is debugging information that should not be masked".
 *
 * And **first level already knows who reported this feedback** (the backend stores the actor from
 * the login identity),
 * so carrying logid exposes no extra person's identity. First level is exactly the one that needs
 * it most:
 * those records are left without the user knowing, with nobody around to explain "what I was
 * doing then";
 * only a logid can link it back to that request's scene on the server.
 *
 * ⚠️ A hard rule on the backend comes with it: **logid must never go into dedup_key** (it is unique
 * per request; in the key
 * every row would count as new, and rate limiting would fail entirely). Now that first level collects
 * it too, this matters even more: first level is what goes through dedup.
 *
 * # ⚠️ Under `network_error` there is no logid, and that is not a missed read
 *
 * fetch only rejects when the network layer fails, and then **the request never reached the
 * server**: the HTTP middleware that generates the logid
 * never ran, and server logs have not a single line for this request. So in that case
 * there is no logid to fill in, **and none should be made up**; see `ApiError.logId` in
 * data/http.ts.
 *
 * # Collection must never make the page fail
 *
 * Every collection function must be able to return an empty value in the worst case: `navigator`
 * missing fields, `location` altered,
 * the route table changed. **The right behavior when collection fails is to collect one field
 * less, not to throw**:
 * a "report a problem" feature blowing up the page itself is the ugliest failure here.
 */

import type { AsyncError } from "@/lib/useAsyncData";

/** Summary of one API call. **Only second level reports it.** */
export interface FeedbackCall {
  method: string;
  path: string;
  status: number;
  code: string;
  /**
   * The server's logid for that request; **empty string if unavailable** (network failure, or the
   * response header not exposed cross-origin).
   *
   * This one can actually save the `network_error` case: the failing request itself has no logid
   * (it never arrived),
   * but if the user used it normally for a while before the backend went down, the earlier
   * failures that **did reach** the server
   * each carry a real logid; following them pinpoints when the backend went down.
   */
  logId: string;
}

/**
 * Report payload. Fields match the backend's `core.FeedbackInput` one to one.
 *
 * ⚠️ **Before adding a field, make sure the backend accepts it**: the backend decodes by allowlist,
 * and extra fields sent from here are silently dropped,
 * showing up as "I clearly sent it, but cannot find it".
 */
export interface FeedbackPayload {
  level: "auto" | "user";
  routePattern: string;
  httpStatus: number;
  errorCode: string;
  errorKind: string;
  message: string;
  workspaceId?: string;
  browser: string;
  os: string;
  appVersion: string;
  /**
   * The server's logid for this request. **Collected at both levels** (it needs no user consent;
   * see "why logid is collected at both levels" in the file header).
   *
   * Only errors with a response (403 / 404 / 409 / 500…) have it; under `network_error` it is
   * **always absent**:
   * the request never reached the server, the middleware never ran, no id was generated. Then this
   * key does not exist at all,
   * rather than being set to an empty string or some placeholder.
   */
  logId?: string;
  /**
   * The endpoint that failed: method + route pattern with ids removed. **Collected at both levels.**
   *
   * `routePattern` is the **page** route, these two are the **API** route, and they often differ:
   * one page `/w/{id}/chat` calls a dozen endpoints. And first level does not collect `recent`,
   * so before this, first-level records could not show "which endpoint failed" at all,
   * which is the first question to answer when debugging.
   *
   * The reasons it is not sensitive are the same as for `routePattern`, point by point: a pattern
   * string (ids removed), no query,
   * no user input, not a credential; it is just an item in our own public API list.
   *
   * When unavailable (an exception that is not an ApiError) these two keys are absent, not empty
   * strings.
   */
  apiMethod?: string;
  apiRoute?: string;
  /** The following four **only appear at second level** (first level never sets these keys). */
  path?: string;
  agentId?: string;
  recent?: FeedbackCall[];
  consoleErrors?: string[];
}

/** Context available from the page at collection time. The caller (component) provides the part it knows. */
export interface FeedbackContext {
  /** Current workspace id (starting with `ws_`). **Not the key**: the backend only accepts the id. */
  workspaceId?: string;
  /** Current agent id; only the chat page and the agent detail page have it. */
  agentId?: string;
}

/** How many recent API calls / console errors to keep at most. Matches the backend's cap (it truncates beyond that too). */
const MAX_RECENT = 10;

/**
 * Ring buffer: the last few failed API calls.
 *
 * # Why only failures are recorded
 *
 * Recording all calls would need a hook on the success path of `request()` too, which every request
 * on the site goes through;
 * and when debugging an error, **the earlier successful calls give almost no information**. What
 * is really useful is
 * "before this endpoint failed, were other endpoints failing too": that tells "one endpoint is
 * broken"
 * from "the whole backend is down", and that distinction only needs failure records.
 *
 * # Why a module-level variable
 *
 * It is a pure cache: losing it only means collecting a few fewer fields, with no effect on any
 * feature. The frontend is a single process, single page,
 * so the backend's rule "in-process state is wrong with multiple instances" does not apply.
 */
let recentFailures: FeedbackCall[] = [];

/**
 * Record one failed API call. Called by `data/http.ts` at its single error exit.
 *
 * ⚠️ **The path need not have ids removed before being passed in**: they are removed here
 * (`stripIDs`), and the backend removes them again.
 * Removing on both sides is deliberate: only second level reports this data, but the buffer
 * collects under both levels,
 * and in case someone wires it into first level later, data with ids removed is the safe default.
 */
export function recordFailedCall(
  method: string,
  path: string,
  status: number,
  code: string,
  logId = "",
): void {
  try {
    recentFailures.push({
      method,
      // Cut the query first, then remove ids: the query may contain a token (identity really did
      // go into ?actor= in the past).
      path: stripIDs(stripQuery(path)),
      status,
      code,
      // Store an empty string as empty, **with no placeholder fallback**: no logid and "a logid that
      // cannot be found"
      // are two different things when debugging; the latter makes people search for nothing (see
      // ApiError.logId).
      logId,
    });
    if (recentFailures.length > MAX_RECENT) {
      recentFailures = recentFailures.slice(-MAX_RECENT);
    }
  } catch {
    // Collection must not affect the main flow. This should never throw in theory, but it sits on
    // the path of every failed request,
    // so it is worth a fallback layer: an "error recording" action that throws itself would cover
    // up the real error scene.
  }
}

/** Clear the buffer. For e2e, so test cases do not pollute each other. */
export function clearRecentCalls(): void {
  recentFailures = [];
}

/**
 * Ring buffer: the **first line** of the last few console errors.
 *
 * Keeping only the first line is deliberate: full stacks contain source paths, variable names,
 * and occasionally inline data.
 * The first line (`TypeError: x is not a function`) is enough for diagnosis, and it almost never
 * contains user data.
 */
let recentConsoleErrors: string[] = [];

/**
 * Start capturing console errors. Called once in `main.tsx`.
 *
 * **Wraps console.error rather than listening to window.onerror**: most valuable errors are
 * caught by
 * React or by us and then `console.error`'d (`useAsyncData` does exactly that),
 * and those never trigger onerror.
 *
 * ⚠️ **Forward to the original function unchanged**, not a single character altered: the console
 * is the main scene for debugging,
 * and a collection feature silencing it is unacceptable.
 */
export function installConsoleCapture(): void {
  const original = console.error;
  console.error = (...args: unknown[]) => {
    try {
      const first = args
        .map((a) => (a instanceof Error ? a.message : typeof a === "string" ? a : ""))
        .filter(Boolean)
        .join(" ")
        .split("\n")[0];
      if (first) {
        recentConsoleErrors.push(first.slice(0, 300));
        if (recentConsoleErrors.length > MAX_RECENT) {
          recentConsoleErrors = recentConsoleErrors.slice(-MAX_RECENT);
        }
      }
    } catch {
      // Same as above: if collection fails, collect one less; it must never affect console.error
      // itself.
    }
    original(...args);
  };
}

/** Clear the console error buffer. For e2e. */
export function clearConsoleErrors(): void {
  recentConsoleErrors = [];
}

/**
 * Cut the query and fragment off a URL.
 *
 * **Must be cut**: the query may contain credentials. This repo's SSE subscription really did put
 * identity into
 * `?actor=` in the past (see the comment in data/http.ts), and any feature that "reports the
 * current URL"
 * would carry such parameters along.
 */
function stripQuery(s: string): string {
  const i = s.search(/[?#]/);
  return i >= 0 ? s.slice(0, i) : s;
}

/**
 * Replace path segments that look like ids with `{id}`.
 *
 * The check is **the shape of the segment**, kept in line with the backend's `stripRouteIDs` (both
 * sides do it; see the file header):
 * opaque ids with underscores (`ws_x` / `agent_x` / `run_x`), **timestamp-style ids with hyphens**
 * (`sesn-20260101000000-abcde`), pure numbers, long hex strings, UUIDs.
 *
 * ⚠️ **The hyphen rule was only found end to end**: real session ids are
 * `sesn-<14-digit timestamp>-<random>`,
 * with not a single underscore, so the original three rules **all missed** them, and first-level
 * reports stored route_pattern
 * with real session ids. That both leaked "which conversation this person was just in" (first level
 * has no user consent)
 * and destroyed the field's value for aggregation (a different value per conversation, so "which
 * page errors most" could not be answered).
 *
 * This hole could not be caught by tests because the mock seed data uses ids like `run_1` **with
 * underscores**,
 * while production ones start with `sesn-`. **The same field has different shapes in the two
 * environments**, so e2e was all green.
 *
 * Short all-letter segments are deliberately **not** removed: those are route literals (`agents` /
 * `settings` / `chat`),
 * and removing them would make all routes look the same, making this field useless.
 */
/**
 * The "route patterning" entry reused by `data/http.ts`: **cut the query first, then remove ids**.
 *
 * The order must not be reversed, for the same reason as the comment in `recordFailedCall`: the
 * query may carry a token
 * (identity really did go into `?actor=` in the past); removing ids first would leave that part in
 * place until it is cut later,
 * and if anyone used the intermediate product it would leak. Combining them into one function
 * means
 * **callers have no chance to get the order wrong**.
 */
export function routePatternForReport(path: string): string {
  return stripIDs(stripQuery(path));
}

function stripIDs(path: string): string {
  return path
    .split("/")
    .map((seg) => {
      if (!seg) return seg;
      if (seg.startsWith("{") && seg.endsWith("}")) return seg;
      if (seg.includes("_")) return "{id}";
      if (/^\d+$/.test(seg)) return "{id}";
      // Has hyphens and one part is a long digit string (≥8 digits, i.e. a date/timestamp):
      // `sesn-20260101000000-abcde`.
      // Requiring "a digit part" rather than just "has a hyphen", otherwise `ark-agent`, `skill-hub`
      // and similar **route literals and workspace keys** would be removed too, ruining the field.
      if (seg.includes("-") && /(^|-)\d{8,}(-|$)/.test(seg)) return "{id}";
      if (seg.length >= 16 && /^[0-9a-fA-F-]+$/.test(seg)) return "{id}";
      if (seg.length === 36 && (seg.match(/-/g)?.length ?? 0) === 4) return "{id}";
      return seg;
    })
    .join("/");
}

/**
 * The pattern string of the current route: `/w/growth/chat/run_abc` → `/w/{id}/chat/{id}`.
 *
 * # Why not react-router's useMatches()
 *
 * That would be more precise (it gives real parameter names like `:workspaceKey`), but it is a hook,
 * and first-level reporting happens in `useAsyncData`'s catch, which is not render time; hooks
 * cannot be called there.
 * Letting callers fetch it first and pass it in would also work, but that requires 13 error-state
 * call sites to each pass it,
 * and missing one silently becomes an empty string.
 *
 * Removing by shape **can be called anywhere**, at the cost that workspace keys (`growth`, all
 * letters) are not removed.
 * That cost is acceptable: a workspace key is not sensitive (it is in the URL, in titles, visible
 * to everyone),
 * and keeping it actually makes "which workspace errors most" visible.
 */
export function currentRoutePattern(): string {
  try {
    return stripIDs(window.location.pathname);
  } catch {
    return "";
  }
}

/** The current full path (with ids, query cut). **Only second level reports it.** */
function currentPath(): string {
  try {
    return stripQuery(window.location.pathname);
  } catch {
    return "";
  }
}

/**
 * Browser summary, like `Chrome 120`.
 *
 * ⚠️ **The raw UA string is deliberately not reported.** The raw UA is nearly a fingerprint (the
 * combination of version + platform + rendering engine
 * can narrow down to a very small group), while diagnosis only needs "which browser". So it is
 * summarized here,
 * so the raw string **never leaves the browser**, rather than sending it to the backend to trim.
 *
 * Order matters: Edge and Chrome UAs both contain `Chrome`, and Chrome's contains `Safari`.
 * So check from the most specific downward.
 */
function browserSummary(): string {
  try {
    const ua = navigator.userAgent;
    const pick = (re: RegExp): string | null => {
      const m = ua.match(re);
      return m?.[1] ? m[1].split(".")[0] : null;
    };
    for (const [name, re] of [
      ["Edge", /Edg\/(\d+)/],
      ["Chrome", /Chrome\/(\d+)/],
      ["Firefox", /Firefox\/(\d+)/],
      ["Safari", /Version\/(\d+)/],
    ] as const) {
      const v = pick(re);
      if (v) return `${name} ${v}`;
    }
    return "";
  } catch {
    return "";
  }
}

/** OS summary, like `macOS`. Also only the broad kind, no version (versions are fingerprints too). */
function osSummary(): string {
  try {
    const ua = navigator.userAgent;
    if (/Windows/.test(ua)) return "Windows";
    if (/Mac OS X/.test(ua)) return "macOS";
    if (/Android/.test(ua)) return "Android";
    if (/(iPhone|iPad|iPod)/.test(ua)) return "iOS";
    if (/Linux/.test(ua)) return "Linux";
    return "";
  } catch {
    return "";
  }
}

/**
 * Frontend version. Injected as the git sha at build time by `define` in vite.config.ts.
 *
 * Empty string if unavailable (in `dev` mode, or when the build environment has no .git); **do not
 * fall back to "unknown"**:
 * that would make "not injected" and "injected a version called unknown" look the same in the
 * database.
 */
function appVersion(): string {
  try {
    return typeof __APP_VERSION__ === "string" ? __APP_VERSION__ : "";
  } catch {
    return "";
  }
}

/**
 * Build one report payload.
 *
 * ⚠️ **The split between the two levels happens in this function**, which is the only important
 * thing it does: only when `level === "user"` are
 * those four fields added. The first-level path **has no assignment statements for them at all**:
 * not "set to empty", but those keys do not exist.
 */
export function buildFeedbackPayload(
  level: "auto" | "user",
  error: AsyncError,
  ctx: FeedbackContext = {},
): FeedbackPayload {
  const payload: FeedbackPayload = {
    level,
    routePattern: currentRoutePattern(),
    httpStatus: error.status,
    errorCode: error.code,
    errorKind: error.kind,
    message: error.message,
    browser: browserSummary(),
    os: osSummary(),
    appVersion: appVersion(),
  };
  // The endpoint that failed. **Collected at both levels**; see FeedbackPayload.apiRoute for why.
  // Empty values get no key, same approach as logId: "not captured" and "captured empty" are two
  // different things when debugging.
  if (error.apiRoute) {
    payload.apiRoute = error.apiRoute;
    if (error.apiMethod) payload.apiMethod = error.apiMethod;
  }
  // The workspace id goes with both levels: it does not pinpoint a person or a conversation, and
  // "which workspace has the problem"
  // is useful for diagnosis (e.g. "only that workspace's Ark credentials expired").
  // ⚠️ Only include it when it **looks like an id**: what is at hand on the page is often the key
  // (growth),
  // and once a key is stored this column cannot be joined with the workspace table, and the
  // backend drops it too.
  if (ctx.workspaceId?.startsWith("ws")) {
    payload.workspaceId = ctx.workspaceId;
  }
  // The server logid **goes with both levels**: it is a string our own server generates, with none
  // of the user's input,
  // and not a credential, so it needs no user consent; and first level already knows "who reported
  // this feedback"
  // (the backend takes the actor from the login identity). First level needs it most: those records
  // have no user around to explain
  // "what I was doing then"; only a logid can link it back to that request's scene on the server.
  //
  // **When empty this key does not exist** (same as agentId), rather than being set to empty:
  // "there was no server logid this time" and "there is an empty logid" are two different things
  // when debugging,
  // and describePayload's empty-value filter uses it to skip that whole row: under `network_error`
  // the panel will not show an empty "server log ID", which is exactly the honesty we want.
  if (error.logId) payload.logId = error.logId;

  if (level === "user") {
    // ---- Only reached when the user clicks "report this problem" ----
    payload.path = currentPath();
    if (ctx.agentId) payload.agentId = ctx.agentId;
    if (recentFailures.length > 0) payload.recent = [...recentFailures];
    if (recentConsoleErrors.length > 0) payload.consoleErrors = [...recentConsoleErrors];
  }
  return payload;
}

/**
 * First-level automatic record: report silently when a failure happens, **without waiting for it
 * or caring whether it succeeds**.
 *
 * # Why this function is here and not in useAsyncData
 *
 * It used to be a private function of `useAsyncData`, so **only read failures were recorded
 * automatically**,
 * while write failures (sending messages, creating agents, saving settings) never pass through that
 * hook and were never recorded.
 * That was not a bug but a missed path back then: first level means "record on any error",
 * not "record on load errors". Putting it here lets both paths share one implementation,
 * rather than writing one each and drifting sooner or later.
 *
 * # Why api is imported dynamically
 *
 * `data/api.ts` → `data/http.ts` → `lib/feedback.ts` is already a chain,
 * and a static import of `data/api.ts` from this file would form a cycle. ESM circular imports
 * **give no error**:
 * they make one of the modules get `undefined` at init time, showing up as "some page occasionally
 * blank"
 * with an error pointing somewhere completely unrelated. A dynamic import resolves **at call
 * time**, when everything is initialized.
 *
 * # Why the whole function is wrapped in catch
 *
 * It runs on the error-handling path. **Anything thrown here would cover up the real error
 * scene**,
 * and the scene is the only basis for debugging. So import failures, api not initialized, the
 * report itself failing: all swallowed.
 *
 * ⚠️ **Callers must not await it**: reporting is a side path; awaiting would make the error-state
 * render wait one extra network round trip,
 * so users would pay latency for a feature they do not know exists. But it also **must not be
 * written as `void p`**:
 * that does not guard against rejection, and an unhandled rejection here would cover up the really
 * useful console.error.
 * The right way is `void reportAutoFeedback(err)` (this function itself never rejects).
 */
export async function reportAutoFeedback(error: AsyncError): Promise<void> {
  try {
    const { api } = await import("@/data/api");
    // First level carries no workspace/agent context: those must come from the render layer, which
    // is not reachable here,
    // and **we deliberately do not go get them**: first level's collection surface should be minimal.
    await api.submitFeedback(buildFeedbackPayload("auto", error));
  } catch {
    // Silent. See the third section above.
  }
}

/**
 * First-level report for long-lived connection (SSE / WebSocket) failures.
 *
 * # Why this cannot go through reportAutoFeedback
 *
 * That function takes an `AsyncError`, which comes from `classifyError`, whose raw material is a
 * **rejected Promise**. Long-lived connections have no such thing: the event object
 * `EventSource.onerror` gets
 * **has no status code, no response body, no error message** (the spec says so, to avoid leaking
 * cross-origin information). So the payload is built here, and `httpStatus` is always 0, with the
 * same meaning as
 * `network_error`: **no HTTP response was received**, not "received 0".
 *
 * # ⚠️ Why the `alive` gate is required (this is the pivot of the whole feature)
 *
 * After a session ends, the container idles into pause and is reclaimed by the platform after the
 * TTL (1 hour). When a user later opens that
 * finished session, the terminal cannot connect; **that is the expected result, not a fault**.
 * Reporting unconditionally would make **every historical session that is opened add a feedback
 * row**, and those records
 * all differ (ids are removed from routePattern, but error codes and times vary), so dedup cannot
 * hold the volume.
 * Noise drowning real problems is worse than not collecting: the inspection agent would be fed a
 * pile of "normal behavior".
 *
 * So the check is **look up whether the container still exists at the moment of failure**
 * (`api.getRunSandbox`):
 *
 *   - `running` → the container is alive but cannot be reached; **a real fault, report it**;
 *   - `none` / `paused` / `gone` → expected, stay quiet;
 *   - cannot tell (this lookup also failed) → **also stay quiet**. The direction is chosen on
 *     purpose:
 *     better to miss one than to flood. Real faults are usually reproducible, and the user will
 *     click again.
 *
 * This check can be trusted because the backend already separates the two (`RunSandboxState` in
 * `core/sandbox.go`):
 * when it cannot connect, **only 404 counts as `gone`**, and other errors all surface as 500
 * rather than falsely claiming "reclaimed". So `gone` is an authoritative conclusion, not a guess.
 *
 * # Why look it up live, rather than use the status the component holds
 *
 * The component's `status` was fetched **when entering the page**. The terminal never connects when
 * not running
 * (`SandboxTerminal` returns at the top), so by the time "connection failed" is reached it is always
 * `running`;
 * using it as the check would be always true, making the gate pointless. The container goes away
 * exactly between those two moments.
 */
export async function reportConnectionFailure(
  errorCode: string,
  message: string,
  runId: string,
): Promise<void> {
  try {
    const { api } = await import("@/data/api");
    // Look it up once. **This step is the check itself**; removing it means reporting
    // unconditionally.
    const state = await api.getRunSandbox(runId);
    if (state.status !== "running") return;
    await api.submitFeedback({
      level: "auto",
      routePattern: currentRoutePattern(),
      // 0 = no HTTP response was received. EventSource error events have no status code to begin
      // with;
      // **do not make one up** (same as logId: a value that cannot be found is worse than no
      // value).
      httpStatus: 0,
      errorCode,
      errorKind: "other",
      message,
      browser: browserSummary(),
      os: osSummary(),
      appVersion: appVersion(),
    });
  } catch {
    // Silent, for the same reason as reportAutoFeedback: this path handles errors, and throwing
    // would cover up the scene.
    // A failed lookup also lands here, which is exactly the "cannot tell, stay quiet" above.
  }
}

/**
 * Turn the payload into "information to be reported" for the user to see.
 *
 * # Why this function is required
 *
 * **One-click reporting without the user knowing what is sent is unacceptable.** So next to the
 * feedback entry there is an expandable
 * "view information to be reported", whose content comes from here, and it renders **the very
 * object that will be sent**,
 * not text describing it. Text drifts from the implementation; the object does not.
 *
 * Returns an array of `[label, value]` rather than raw JSON: JSON is unfriendly to users, and this
 * panel's
 * purpose is to let people **understand** it, not verify bytes.
 */
export function describePayload(
  payload: FeedbackPayload,
  t: (key: string) => string,
): { label: string; value: string }[] {
  const rows: { label: string; value: string }[] = [];
  const add = (label: string, value: string | number | undefined): void => {
    if (value === undefined || value === "" || value === null) return;
    rows.push({ label, value: String(value) });
  };
  add(t("feedback.fieldRoute"), payload.routePattern);
  add(t("feedback.fieldStatus"), payload.httpStatus || undefined);
  add(t("feedback.fieldCode"), payload.errorCode);
  add(t("feedback.fieldMessage"), payload.message);
  add(t("feedback.fieldBrowser"), [payload.browser, payload.os].filter(Boolean).join(" / "));
  add(t("feedback.fieldVersion"), payload.appVersion);
  add(t("feedback.fieldWorkspace"), payload.workspaceId);
  // Server logid, **present at both levels** (so it is in the shared section).
  // **If absent the whole row is not shown** (the empty-value filter in add above skips
  // undefined): under `network_error`
  // the server has no log of this request at all, and showing an empty row or placeholder would
  // make people think
  // "there is an id that just is not shown", then search for nothing.
  add(t("feedback.fieldLogID"), payload.logId);
  // The failing endpoint, **present at both levels**, so it is also in the shared section.
  //
  // ⚠️ This row must appear on the panel: this expandable area renders **the very object that will
  // be sent**;
  // adding a field without showing it means "the list the user sees ≠ what is actually reported",
  // which is the one mistake this feature must never make (written down in README-feedback.md).
  //
  // ⚠️ **e2e does not cover this row; do not assume it is tested.** `LocalApiClient` does not go
  // through
  // `request()` in `data/http.ts`; its errors are created directly by `mockApiError`,
  // which has no "which endpoint was just being called" information, so in mock mode `apiRoute` is
  // always empty,
  // this row **never renders**, and any test asserting it would always pass (exactly what this repo
  // has noted as
  // "the same field has two shapes in test and production").
  // What really pins this chain down are the two Go tests on the backend
  // (`TestFeedbackAPIRouteIsSanitized` / `TestAutoAndUserCollectDifferentFields`)
  // plus TS type checking. To cover it in e2e, the mock must first carry the route too.
  add(
    t("feedback.fieldAPI"),
    [payload.apiMethod, payload.apiRoute].filter(Boolean).join(" ") || undefined,
  );
  // The items only second level has. Use counts rather than contents: the panel must be readable at
  // a glance,
  // and "includes the last 3 API calls" already says clearly what will be reported.
  add(t("feedback.fieldPath"), payload.path);
  add(t("feedback.fieldAgent"), payload.agentId);
  if (payload.recent?.length) {
    add(t("feedback.fieldRecent"), String(payload.recent.length));
  }
  if (payload.consoleErrors?.length) {
    add(t("feedback.fieldConsole"), String(payload.consoleErrors.length));
  }
  return rows;
}
