/**
 * Parses the marked-up text in container tool results.
 *
 * The backend **does not** turn the exit code / stdout / stderr into structured fields: the
 * `agent.tool_result` payload
 * only has `content: ContentBlock[]` plus an `is_error` boolean. The real execution details are
 * joined into one block of text by `formatResult()` in `server/shared/infra/shelltools/bash.go` and
 * put into content:
 *
 *     exit_code: 0                       ← always the first line
 *     --- sandbox error ---              ← optional: error from sandboxd (container did not start)
 *     ...
 *     --- stdout ---                     ← optional
 *     ...
 *     --- stderr ---                     ← optional
 *     ...
 *     …（输出过长，已截断，共 N 字节）      ← appended when over 64 KiB (literal text from Go:
 *                                            "output too long, truncated, N bytes total")
 *
 * So "showing the exit code and container logs" can only be done by splitting it back in the
 * frontend. **This is an implicit contract with the Go side**:
 * changing the format of `formatResult()` silently breaks this (the page falls back to showing the
 * whole block, with no error).
 * Both sides have comments pointing at each other; when changing one side, check the other.
 *
 * Only bash uses this format. MCP, read/write/edit/glob/grep results, and seed data have no markers;
 * those take the fallback path (`structured: false`), and the caller shows the whole block as is.
 */

/** The structure that can be split out of the result text. Fields that cannot be split are undefined; nothing is faked. */
export interface ParsedToolResult {
  /** Numeric exit code. */
  exitCode?: number;
  /** The process has not exited (the Go side writes the literal Chinese `(未退出)`, meaning "not exited"). */
  exitState?: "not_exited";
  /** Execution error reported by sandboxd. Not the same as the process's stderr: this means the command never ran. */
  sandboxError?: string;
  stdout?: string;
  stderr?: string;
  /** The backend truncated at 64 KiB. Without a note at the cut, readers would take it as the real end of the output. */
  truncated: boolean;
  /** No exit_code line was recognized → false; the caller falls back to showing the whole block as is. */
  structured: boolean;
}

/**
 * Section markers. **Must be line-anchored** (`^...$` + multiline).
 *
 * Cannot use `text.split("---")`: `---` in stdout is very common (markdown separators,
 * diff's `--- a/file`); splitting that way would chop a log into pieces, and where it chops wrong
 * depends on the content.
 */
const SECTION_RE = /^--- (sandbox error|stdout|stderr) ---$/;

/** The `fmt.Fprintf(&b, "exit_code: %s\n", code)` line on the Go side. */
const EXIT_CODE_RE = /^exit_code: (.+)$/;

/** The note the Go side appends when over the limit; see truncate() in bash.go. */
const TRUNCATED_RE = /…（输出过长，已截断，共 \d+ 字节）\s*$/;

/** `(未退出)` is a literal generated by Go, not UI text: it does not change with language, and must not be compared via t(). */
const NOT_EXITED = "(未退出)";

type SectionName = "sandbox error" | "stdout" | "stderr";

export function parseToolResult(text: string): ParsedToolResult {
  const empty: ParsedToolResult = { truncated: false, structured: false };
  if (!text) return empty;

  const truncated = TRUNCATED_RE.test(text);
  // Remove the truncation note before splitting into sections: Go appends it at the very end, and
  // if not removed it mixes into the body of the last section,
  // whose body is shown as stdout/stderr as is. Truncation is expressed by a separate flag.
  const lines = (truncated ? text.replace(TRUNCATED_RE, "") : text).split("\n");

  // The first line must be exit_code. **This is the only check**, not "has any section marker":
  // the chance that another tool's output happens to contain `--- stdout ---` is not zero, and
  // rendering it as structured then
  // would break a normal log into scattered pieces.
  const head = EXIT_CODE_RE.exec(lines[0] ?? "");
  if (!head) return empty;

  const out: ParsedToolResult = { truncated, structured: true };

  const rawCode = head[1].trim();
  if (rawCode === NOT_EXITED) {
    out.exitState = "not_exited";
  } else {
    const n = Number(rawCode);
    if (Number.isInteger(n)) out.exitCode = n;
  }

  // Scan line by line into sections. Section content is kept as is (only leading/trailing blank
  // lines trimmed), so stdout can be read back word for word.
  const buckets = new Map<SectionName, string[]>();
  let current: SectionName | null = null;

  for (let i = 1; i < lines.length; i++) {
    const m = SECTION_RE.exec(lines[i]);
    if (m) {
      current = m[1] as SectionName;
      if (!buckets.has(current)) buckets.set(current, []);
      continue;
    }
    // Lines before any section marker (normally none) are dropped, to avoid putting them in the
    // wrong section.
    if (current) buckets.get(current)!.push(lines[i]);
  }

  const take = (name: SectionName): string | undefined => {
    const body = buckets.get(name);
    if (!body) return undefined;
    const s = body.join("\n").replace(/^\n+/, "").replace(/\n+$/, "");
    return s || undefined;
  };

  out.sandboxError = take("sandbox error");
  out.stdout = take("stdout");
  out.stderr = take("stderr");

  return out;
}
