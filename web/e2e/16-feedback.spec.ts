/**
 * One-click problem feedback: the collection boundaries of the two levels, rate limiting, and "you can
 * see what will be sent before reporting".
 *
 * # The regressions this spec guards against
 *
 * This feature has three failure modes that "cause no error when broken", each only visible end to end:
 *
 * 1. **Level one quietly collects more.** The collection boundary is decided when the frontend builds
 *    the payload (`buildFeedbackPayload` in `lib/feedback.ts`); the backend is only the second line.
 *    If someday someone took a shortcut and let both levels share one payload, level one would start
 *    reporting full paths, agent ids, API traces, and **nothing would show in the UI**, with all tests
 *    green. So this reads the records the mock stored and asserts key by key.
 * 2. **Rate limiting stops working.** Without dedup, one bad API would flood the table instantly,
 *    while during development you only see "works fine" (one can be stored, a hundred can be stored).
 * 3. **No receipt appears.** If clicking shows no response, users click again and again, and every
 *    click is a new record.
 *
 * # Why read the mock instead of asserting the UI
 *
 * "What was reported" is not shown in the UI at all (except that expandable panel). Checking the field
 * set means looking at the stored data, so `LocalApiClient` stores received feedback in a separate
 * localStorage key, and `feedbackReports()` reads it. This splits the work with "the backend half is
 * checked by Go unit tests": **this checks what the frontend sent, Go checks what the backend stored.**
 */

import {
  clearFeedbackMock,
  expect,
  failReadsMock,
  failWritesMock,
  feedbackReports,
  restoreReadsMock,
  restoreWritesMock,
  test,
} from "./fixtures";

// Feedback lives in a separate localStorage key (reset() cannot wipe it), so clear it before each case.
// Otherwise the previous case's reports would turn the count assertions below red on the second run.
test.beforeEach(async ({ app }) => {
  await clearFeedbackMock(app);
});

test.afterEach(async ({ page }) => {
  await restoreReadsMock(page);
  await restoreWritesMock(page);
  await clearFeedbackMock(page);
});

test.describe("一级：自动记录", () => {
  test("加载失败会自动记一条，用户不用点任何东西", async ({ app }) => {
    await failReadsMock(app, "internal");
    await app.goto("/w/growth");
    await expect(app.getByTestId("load-error")).toBeVisible();

    // Reporting is fired off with `void` (no await, see the comment in useAsyncData), so poll.
    await expect
      .poll(async () => (await feedbackReports(app)).filter((r) => r.level === "auto").length)
      .toBeGreaterThan(0);

    const auto = (await feedbackReports(app)).find((r) => r.level === "auto")!;
    // The three-part diagnosis must really be included: that is why AsyncError adds status/code.
    // Before that, these two fields were unavailable, and a feedback entry could only say "someone hit an error".
    expect(auto.errorCode).toBe("internal");
    expect(auto.httpStatus).toBe(500);
    // The route pattern must erase ids. `growth` is a workspace key (letters only), which cannot and
    // should not be erased by shape: it is not sensitive, and keeping it shows "which workspace errors most".
    expect(auto.routePattern).toBe("/w/growth");
  });

  test("一级不采完整路径、agent、接口轨迹与控制台错误", async ({ app }) => {
    // Pick a page whose URL **really has an id**: if level one wrongly collected the path, that agent id
    // would show up here. The overview page (no id in the URL) cannot test this.
    //
    // ⚠️ Use the agent detail page, not the run detail page: `guardRead` only wraps a few **list** methods
    // (listAgents / listSkills / listFeishuApps / listApiKeys / listRuns),
    // and does not wrap `getRun`, so the run detail page never fails under failReads.
    // This is not a mock defect; it deliberately only covers list reads. Hit once and recorded here, so
    // next time nobody tests the error state on a page that cannot fail.
    await failReadsMock(app, "internal");
    await app.goto("/w/growth/agents/agent_triage");
    await expect(app.getByTestId("load-error")).toBeVisible();

    await expect
      .poll(async () => (await feedbackReports(app)).filter((r) => r.level === "auto").length)
      .toBeGreaterThan(0);

    const auto = (await feedbackReports(app)).find((r) => r.level === "auto")!;
    // ⚠️ These four are the feature's **collection boundary**; not one may be loosened.
    // The user did not click anything, so no identifier that can pin down a specific business object
    // should be collected.
    expect(auto.path).toBeUndefined();
    expect(auto.agentId).toBeUndefined();
    expect(auto.recent).toBeUndefined();
    expect(auto.consoleErrors).toBeUndefined();
    // ⚠️ **logid is the exception: level one collects it too.** It is a string generated by the server
    // itself, contains no user input, and is not a credential, and level one already knows "who reported
    // this" (the backend takes the actor from the login identity). The assertion is here (rather than in a
    // separate case) on purpose: with both sides of the boundary side by side, readers see at a glance
    // **what should be blocked and what should not**. Writing only the "not collected" half would make the
    // next person think "the less in level one the better" and delete it along the way.
    expect(auto.logId).toContain("mocklogid-");
    // The agent id in the route pattern must already be erased into a placeholder.
    expect(auto.routePattern).toBe("/w/growth/agents/{id}");
    expect(auto.routePattern).not.toContain("agent_triage");
  });

  test("同一个错误刷多次只记一条，靠 occurrences 记量级", async ({ app }) => {
    await failReadsMock(app, "internal");

    // Enter the same page 4 times: each triggers one load failure and sends one level-one report.
    for (let i = 0; i < 4; i++) {
      await app.goto("/w/growth");
      await expect(app.getByTestId("load-error")).toBeVisible();
    }

    await expect
      .poll(async () => {
        const autos = (await feedbackReports(app)).filter((r) => r.level === "auto");
        return autos[0]?.occurrences ?? 0;
      })
      .toBeGreaterThan(1);

    const autos = (await feedbackReports(app)).filter((r) => r.level === "auto");
    // ⚠️ **This is the evidence of rate limiting**: 4 reports, only 1 row.
    // Without dedup this would become 4, while the feature looks completely normal on the surface.
    expect(autos).toHaveLength(1);
    // The magnitude must not be lost: merged into one row, but it must say how many times it happened.
    expect(autos[0].occurrences).toBeGreaterThan(1);
  });
});

test.describe("二级：用户主动反馈", () => {
  test("错误态上有反馈入口，点了给回执", async ({ app }) => {
    await failReadsMock(app, "internal");
    await app.goto("/w/growth");
    await expect(app.getByTestId("load-error")).toBeVisible();

    const button = app.getByTestId("feedback-submit");
    await expect(button).toBeVisible();
    await button.click();

    // The receipt must be visible. Assert the data attribute rather than the text: it is an observation
    // point left for "no mouse" scenarios (same as RunTimeline's CopyButton); a tooltip alone cannot be
    // observed in e2e.
    await expect(app.locator('[data-feedback-state="sent"]')).toBeVisible();
    await expect(button).toContainText("已收到，谢谢");
  });

  test("403 也给反馈入口", async ({ app }) => {
    // A 403 looks like "the user's own problem", but it is exactly the most common source of false
    // alarms in this repo (the 12 blank screens fixed in useAsyncData that time were caused by 403s).
    await failReadsMock(app, "access_denied");
    await app.goto("/w/growth");

    await expect(app.getByTestId("load-denied")).toBeVisible();
    // There should still be no retry button (that existing rule must not be broken by this change).
    await expect(app.getByTestId("load-retry")).toHaveCount(0);
    // But the feedback entry must be there.
    await expect(app.getByTestId("feedback-submit")).toBeVisible();
  });

  test("二级比一级采得多，且带上完整路径", async ({ app }) => {
    // Same as above: use the agent detail page (it has an id in the URL, and failReads really makes it fail).
    await failReadsMock(app, "internal");
    await app.goto("/w/growth/agents/agent_triage");
    await expect(app.getByTestId("load-error")).toBeVisible();

    await app.getByTestId("feedback-submit").click();
    await expect
      .poll(async () => (await feedbackReports(app)).filter((r) => r.level === "user").length)
      .toBe(1);

    const reports = await feedbackReports(app);
    const user = reports.find((r) => r.level === "user")!;
    const auto = reports.find((r) => r.level === "auto")!;

    // ⚠️ **This is the evidence that "the two levels really collect different field sets".**
    // Same page, same error: level two has path and level one does not.
    expect(user.path).toBe("/w/growth/agents/agent_triage");
    expect(auto.path).toBeUndefined();
    // Level two carries the recent failed API calls (level one does not). In local mode LocalApiClient
    // sends no requests, so recent may be empty: **this only asserts "level one definitely has none"**,
    // not "level two definitely has some", or this case would depend on mock implementation details.
    expect(auto.recent).toBeUndefined();
  });

  test("上报前能展开看到将要上报的内容", async ({ app }) => {
    await failReadsMock(app, "internal");
    await app.goto("/w/growth");
    await expect(app.getByTestId("load-error")).toBeVisible();

    // Collapsed by default: the error state should not start out as a wall of information.
    //
    // ⚠️ Assert **not visible**, not `toHaveCount(0)`: HeroUI's `Disclosure.Content` collapses with CSS
    // (`height` + `opacity: 0` + `overflow: clip`, see its BEM styles), and the content **stays mounted in
    // the DOM**. toHaveCount(0) would be red, and that failure message ("expected 0, got 1") looks like the
    // component did not render right, not pointing at all to "it is just hidden by CSS".
    await expect(app.getByTestId("feedback-payload")).toBeHidden();

    await app.getByTestId("feedback-details-toggle").click();

    const panel = app.getByTestId("feedback-payload");
    await expect(panel).toBeVisible();
    // The panel shows **the very object to be sent** (describePayload(payload)), not text describing it,
    // so real values can be asserted here.
    await expect(panel).toContainText("/w/growth");
    await expect(panel).toContainText("internal");
    // "What is never reported" must also be written where users can see it: one-click reporting where users
    // don't know what is sent is unacceptable, and this sentence carries that promise.
    await expect(app.getByTestId("load-error")).toContainText("绝不上报");
  });
});

/*
 * Write failures: **this group came out of a real incident**.
 *
 * A day after one-click feedback launched, the `feedback_reports` table had no records at all. The
 * root cause was not rate limiting and not the backend (curling POST /api/feedback directly returned
 * 204 and the row was stored); it was:
 *
 *   level one only hung off the catch in `useAsyncData`, and that hook **only handles "loading data"**.
 *   Write actions (sending messages, creating agents, saving settings) each try/catch and render an
 *   inline red line, so level one recorded nothing, and level two had no entry either (FeedbackButton
 *   hangs off AsyncErrorBlock).
 *
 * When users hit "failed to send message" both levels failed at once, with zero errors: all the
 * feature code was there, tests were green, the build passed; it just never fired.
 *
 * It was not caught back then because the mock **had no way to create a write failure**: the 7 cases
 * above all use `failReadsMock`, which keeps the page from opening at all, so the question "should a
 * write failure be reported" was never asked in tests. `failWritesMock` was added for exactly this.
 */
test.describe("写操作失败也走两级", () => {
  test("发消息失败会自动记一条一级（这是当初漏掉的那条路径）", async ({ app }) => {
    await app.goto("/w/growth/chat");
    // First let the page load normally (the write-failure switch does not affect reads; the page is fine).
    // That is exactly the difference from failReadsMock: that one keeps the page from opening.
    await expect(app.getByTestId("chat-input")).toBeVisible();

    await failWritesMock(app, "internal");
    await app.getByTestId("chat-input").fill("这条会发失败");
    await app.getByTestId("chat-send").click();

    // The error state must appear (this used to be a bare red line, now it is InlineError).
    await expect(app.getByTestId("chat-error")).toBeVisible();

    // ⚠️ **This assertion is the core of this fix.** Before the fix this was always 0:
    // write failures never called reportAutoFeedback.
    await expect
      .poll(async () => (await feedbackReports(app)).filter((r) => r.level === "auto").length)
      .toBeGreaterThan(0);

    const auto = (await feedbackReports(app)).find((r) => r.level === "auto")!;
    // The three-part diagnosis must be included: 500 + error code, otherwise a feedback entry can only
    // say "someone hit an error".
    expect(auto.httpStatus).toBe(500);
    expect(auto.errorCode).toBe("internal");
    // The collection boundary holds for write failures too: level one carries no full path/agent/trace/console.
    // These four break more easily than on the read side: the chat page has agentId right at hand, easy to
    // slip into level one.
    expect(auto.path).toBeUndefined();
    expect(auto.agentId).toBeUndefined();
    expect(auto.recent).toBeUndefined();
    expect(auto.consoleErrors).toBeUndefined();
  });

  test("发消息失败时错误旁边有反馈入口，点了给回执", async ({ app }) => {
    await app.goto("/w/growth/chat");
    await expect(app.getByTestId("chat-input")).toBeVisible();

    await failWritesMock(app, "internal");
    await app.getByTestId("chat-input").fill("这条会发失败");
    await app.getByTestId("chat-send").click();
    await expect(app.getByTestId("chat-error")).toBeVisible();

    // ⚠️ **This is the direct regression for "the user said they saw no dialog".**
    // Before the fix, a write failure rendered a bare <p>, with nothing clickable on it.
    const button = app.getByTestId("feedback-submit");
    await expect(button).toBeVisible();
    await button.click();
    await expect(app.locator('[data-feedback-state="sent"]')).toBeVisible();

    // Level two must really store a record, collecting more than level one (with the full path).
    await expect
      .poll(async () => (await feedbackReports(app)).filter((r) => r.level === "user").length)
      .toBe(1);
    const user = (await feedbackReports(app)).find((r) => r.level === "user")!;
    expect(user.path).toContain("/w/growth/chat");
    // The chat page has agentId at hand, and level two should include it (that is what the user's
    // consent by clicking buys).
    expect(user.agentId).toBeTruthy();
  });

  test("写失败的错误文案仍然是后端那句话", async ({ app }) => {
    // After switching to useWriteError, message goes through classifyError, which prefers the backend text.
    // This locks in "the text did not change": otherwise what users see would go from the specific reason
    // to the fallback sentence, the silent regression this change is most likely to cause.
    await app.goto("/w/growth/chat");
    await expect(app.getByTestId("chat-input")).toBeVisible();

    await failWritesMock(app, "internal");
    await app.getByTestId("chat-input").fill("这条会发失败");
    await app.getByTestId("chat-send").click();

    const row = app.getByTestId("chat-error");
    await expect(row).toContainText("发送失败");
    // The backend text from guardWrite, not the chat.sendFailedUnknown fallback.
    await expect(row).toContainText("服务端开小差了");
  });
});

/*
 * Server logid: **both levels collect it, but it only exists when the request reached the server.**
 *
 * # The three things this group guards against
 *
 * 1. **Errors with a response missing the logid.** That is this field's main use (errors like
 *    403/404/500 that need cross-side debugging); missing it causes no error, every feedback entry just
 *    lacks the only clue that leads straight to the logs.
 * 2. **Making up a fake logid under `network_error`.** Such failed requests never reached the server,
 *    the middleware that generates logid never ran, and the server logs have not a single line for this
 *    request. Filling in a placeholder would send whoever debugs it on an empty search: **worse than
 *    nothing**.
 * 3. **Level one missing it.** Level one needs it most: those records are left without the user
 *    knowing, nobody is there to explain "what I was doing at the time", and only a logid can connect
 *    it back to the scene. (It needs no user consent: a string generated by the server, with no user
 *    input, and the actor is collected anyway.)
 *
 * # Why the mock has to fake this header
 *
 * The real source is a response header (`X-Request-Id`), and `LocalApiClient` sends no network
 * requests at all. So `guardRead` / `guardWrite` attach a string starting with `mocklogid-` when they
 * create errors (see mockApiError in data/api.ts), while the `network_error` branch **deliberately does
 * not**: that is exactly what this group needs to tell apart.
 */
test.describe("服务端 logid", () => {
  test("有响应的错误（500）两级都采到真 logid", async ({ app }) => {
    await failReadsMock(app, "internal");
    await app.goto("/w/growth/agents/agent_triage");
    await expect(app.getByTestId("load-error")).toBeVisible();

    await app.getByTestId("feedback-submit").click();
    await expect
      .poll(async () => (await feedbackReports(app)).filter((r) => r.level === "user").length)
      .toBe(1);

    const reports = await feedbackReports(app);
    const user = reports.find((r) => r.level === "user")!;
    const auto = reports.find((r) => r.level === "auto")!;

    // ⚠️ **These two are the evidence that "the logid really was read from the response".** Assert the
    // prefix rather than "not empty": the latter also holds for an implementation that "just filled in a
    // constant", which would test nothing.
    expect(user.logId).toContain("mocklogid-");
    // Level one must have it too. **Assert once for each level**: checking only level two, an
    // implementation that "only reads the response header after the user clicks" would be all green, while
    // the level-one half, which needs logid most, is empty.
    expect(auto.logId).toContain("mocklogid-");
  });

  test("403 同样采得到（跨端排查最需要它的场景之一）", async ({ app }) => {
    // A 403 is the most common source of false alarms in this repo, and "which permission check exactly
    // blocked it" can only be told by server logs, so this kind is exactly where logid is most valuable.
    await failReadsMock(app, "access_denied");
    await app.goto("/w/growth");
    await expect(app.getByTestId("load-denied")).toBeVisible();

    await app.getByTestId("feedback-submit").click();
    await expect
      .poll(async () => (await feedbackReports(app)).filter((r) => r.level === "user").length)
      .toBe(1);

    const user = (await feedbackReports(app)).find((r) => r.level === "user")!;
    expect(user.logId).toContain("mocklogid-");
  });

  test("network_error 下不显示、也不上报任何假 logid", async ({ app }) => {
    // ⚠️ **This is the most important assertion in this change.**
    //
    // The scenario in the user's screenshot (/w/ama/usage showing "cannot connect to the server") has this
    // shape: the request never reached the server, so **no logid can be filled in, and none should be**.
    await failReadsMock(app, "network_error");
    await app.goto("/w/growth");
    await expect(app.getByTestId("load-error")).toBeVisible();
    // First confirm what was built really is that error shape, or the assertions below might be testing something else.
    await expect(app.getByTestId("load-error")).toContainText("连不上服务端");

    // That row in the panel must **not appear at all**.
    //
    // ⚠️ Expand the panel before asserting: when `Disclosure.Content` is collapsed the content is still in
    // the DOM (hidden by CSS), and without expanding, the "text does not exist" assertion is a false green:
    // in the collapsed state **no** text is visible, so it cannot tell whether the implementation is right.
    await app.getByTestId("feedback-details-toggle").click();
    const panel = app.getByTestId("feedback-payload");
    await expect(panel).toBeVisible();
    // The panel has other rows (proving it really rendered), but no logid row.
    await expect(panel).toContainText("network_error");
    await expect(panel).not.toContainText("服务端日志 ID");

    // The reported copy must not have it either: the panel and the payload are the same object, but each
    // is pinned once here: "the panel does not show it" and "it is not reported" are two things, and
    // checking only the former, an implementation that "reports it quietly without showing it" would still be green.
    await app.getByTestId("feedback-submit").click();
    await expect
      .poll(async () => (await feedbackReports(app)).filter((r) => r.level === "user").length)
      .toBe(1);

    const user = (await feedbackReports(app)).find((r) => r.level === "user")!;
    expect(user.logId).toBeUndefined();
    // The level-one entry must not have it either. **Assert once for each level**: both levels collect
    // logid, so both can fall into the "fill in a placeholder" trap, and checking only one leaves the
    // other unwatched.
    const auto = (await feedbackReports(app)).find((r) => r.level === "auto")!;
    expect(auto.logId).toBeUndefined();
  });

  test("「最近失败的接口调用」各自带 logid，没到达服务端的那次不带", async ({ app }) => {
    // This locks in **option C**: it is the only way to get a logid in the network_error scenario.
    //
    // How it is built: first make the read API fail with 500 a few times (those "reached the server" and
    // have logids), then switch to network_error ("never reached", no logid), then submit feedback.
    // In the real world this is exactly "used it normally for a while, then the backend went down".
    await failReadsMock(app, "internal");
    await app.goto("/w/growth");
    await expect(app.getByTestId("load-error")).toBeVisible();

    await failReadsMock(app, "network_error");
    await app.goto("/w/growth/agents");
    await expect(app.getByTestId("load-error")).toBeVisible();

    await app.getByTestId("feedback-submit").click();
    await expect
      .poll(async () => (await feedbackReports(app)).filter((r) => r.level === "user").length)
      .toBe(1);

    const user = (await feedbackReports(app)).find((r) => r.level === "user")!;
    // ⚠️ In local mode `LocalApiClient` sends no requests, so recent is empty
    // (recordFailedCall hangs in request() in http.ts, which the mock does not go through).
    // That is not a defect, it is the mock's shape, so this **only asserts its shape when recent has
    // content**, without requiring it to be non-empty; otherwise this case would test mock implementation
    // details instead of our code.
    if (user.recent?.length) {
      // The ones with a logid must be real (the prefix matches); for the ones without, the key must be absent.
      for (const call of user.recent) {
        if (call.logId !== undefined) expect(call.logId).toContain("mocklogid-");
      }
    }
    // This current call is network_error, so the top level definitely has no logid.
    expect(user.logId).toBeUndefined();
  });
});
